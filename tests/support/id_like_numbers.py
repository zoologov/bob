"""Числа, похожие на идентификаторы Telegram, в тексте трекаемой конфигурации (BOB-116).

ОДНА ответственность: найти в тексте каждую серию из шести и более цифр, как бы её ни
разбили. Репозиторий публичный, и id владельца (от шести цифр) или группы (тринадцать) не
должен попасть ни в значение, ни в комментарий. Его гасят разделителем — ``-100_437_294``,
``-100 4372 9473 07``, ``-100-4372-9473-07``, ``-100.4372.9473.07``, табуляцией или
неразрывным пробелом, — поэтому группы цифр, между которыми стоят только разделители,
считаются ОДНОЙ серией, сколько бы разделителей ни стояло подряд и как бы они ни
перемешивались (``-100 - 4372 - 9473 - 07``).

Правило склейки:

* **Разделители:** подчёркивание, дефис, точка, пробел, табуляция, неразрывный, тонкий и
  узкий неразрывный пробелы.
* **Не разделители:** запятая (список ``[600, 3600]`` — это четыре числа), двоеточие
  (время ``06:10``, порт ``:11434``), косая черта и любая буква. Они остаются границей серии.
* **Дата рвёт серию.** Календарная дата ``19YY-MM-DD`` или ``20YY-MM-DD`` с настоящим
  месяцем (01–12) и днём (01–31), не приклеенная к цифре, снимается ДО склейки целиком:
  иначе каждая дата (восемь цифр) и любое число рядом с ней через пробел давали бы ложную
  находку. Дата не склеивается ни с чем вокруг, поэтому id, приписанный к ней дефисом
  (``2026-10-21-1004372947307``), остаётся находкой.

Цена правила, названная заранее, а не найденная позже:

* версия или дробь, у которой вместе шесть цифр и больше (``10.20.300``), — находка: id
  прячут ровно в такой форме (``1.004.372``), и по тексту их не отличить;
* IPv4-литерал (``127.0.0.1`` — шесть цифр) — находка: в трекаемой конфигурации адрес
  пишется именем хоста (``localhost``);
* диапазон, у которого вместе шесть цифр и больше (``21600-86400``), — находка;
* id, у которого восемь цифр подряд образуют настоящую дату, а остаток с каждой стороны
  короче шести цифр, не будет найден. Это единственная форма, которую правило пропускает
  намеренно: цена её поимки — ложная находка на каждой дате в комментарии.

Одно исключение по ключу — значение ``runtime.log_max_bytes`` на его строке (размер ротации
лога). Оно снимается ДО склейки: иначе id, приписанный к значению через пробел, склеился бы
с ним и ушёл вместе с исключением.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

__all__ = ["DigitRun", "has_log_rotation_value", "id_like_digit_runs"]

# Шесть цифр — самый короткий id пользователя Telegram; у группы их тринадцать.
_ID_LIKE_DIGIT_RUN = re.compile(r"\d{6,}")
# Подчёркивание, дефис, точка, пробел, табуляция, неразрывный, тонкий и узкий неразрывный
# пробелы — в любом числе и в любой смеси между двумя цифрами.
_DIGIT_SEPARATOR = re.compile(r"(?<=\d)[_\-. \t   ]+(?=\d)")
# Календарная дата, не приклеенная к цифре: снимается целиком и рвёт серию.
_CALENDAR_DATE = re.compile(
    r"(?<!\d)(?:19|20)\d{2}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01])(?!\d)"
)
# Чем заменяется дата: не цифра и не разделитель, поэтому серия на ней обрывается.
_SERIES_BREAK = "|"
_LOG_MAX_BYTES_VALUE = re.compile(r"^(\s*log_max_bytes:\s*)\d+", re.MULTILINE)


@dataclass(frozen=True, slots=True)
class DigitRun:
    """Одна найденная серия: номер строки (с единицы) и цифры без разделителей."""

    line: int
    digits: str


def id_like_digit_runs(text: str) -> list[DigitRun]:
    """Каждая серия из 6+ цифр в ``text``, кроме значения ``log_max_bytes`` и дат."""
    exempted = _LOG_MAX_BYTES_VALUE.sub(r"\1", text)
    undated = _CALENDAR_DATE.sub(_SERIES_BREAK, exempted)
    joined = _DIGIT_SEPARATOR.sub("", undated)
    return [
        DigitRun(line=number, digits=run)
        for number, line in enumerate(joined.splitlines(), start=1)
        for run in _ID_LIKE_DIGIT_RUN.findall(line)
    ]


def has_log_rotation_value(text: str) -> bool:
    """Есть ли в тексте то значение, ради которого существует исключение."""
    return _LOG_MAX_BYTES_VALUE.search(text) is not None
