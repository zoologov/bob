"""🔴 bob-zmp: ATTEMPTS to read real private-key material through the public entry.

The reproduced CRITICAL was not a code-reading finding — it was a RUN: the live
introspector returned the body of a GitHub-App private key, and would have shipped it
to the external LLM. So this module proves the fix the same way it was found: by
GENERATING a real private key on disk and CALLING the tools a model actually reaches
(``read_file`` behind ``read_code``, ``list_dir``, ``find_file``) against it — in a tmp
repo AND inside the REAL repo tree, where BOB-067's "the whole repo is readable"
invariant would otherwise win. Nothing here inspects the guard's internals.

Three things are asserted, in this order of importance:

1. **Refusal.** Every public path into the file system refuses private-key material
   (:class:`DeniedPathError`), and the file is never opened.
2. **Backstop when the guard MISSES.** A key parked under an ORDINARY name (``notes.md``)
   IS read — and comes back with the key material redacted, because sanitize is the
   second, independent layer (the whole reason the reproduced leak was catastrophic: the
   backstop knew nothing about PEM blocks or ``ghs_`` tokens).
3. **BOB-067 intact.** Ordinary source/dirs in the same tree still read and list — the
   denial is pointed, not a retreat to a whitelist.

The key is a REAL one (``openssl genrsa``) when openssl is on PATH, else a real-SHAPE
synthetic PEM; either way it is generated for this test and never a live credential.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path
from typing import TYPE_CHECKING

import pytest

from bob.capabilities.adapters.introspection.subprocess_introspector import (
    DeniedPathError,
    SubprocessRepoIntrospector,
)
from bob.capabilities.introspection.privacy_guard import PrivacyGuard

if TYPE_CHECKING:
    from collections.abc import Iterator

# This file is tests/infrastructure/introspection/<file> → the repo root is three up.
_REPO_ROOT = Path(__file__).resolve().parents[3]

# A real-shape fallback used only when openssl is unavailable (the guard verdict does not
# depend on the bytes; the sanitize assertions only need a genuine PEM shape).
_SYNTHETIC_PEM = (
    "-----BEGIN RSA PRIVATE KEY-----\n"
    "MIIEpAIBAAKCAQEAnT0fakefakefakefakefakefakefakefakefakefakefake\n"
    "Zm9vYmFyYmF6cXV1eGZha2VmYWtlZmFrZWZha2VmYWtlZmFrZWZha2U=\n"
    "-----END RSA PRIVATE KEY-----\n"
)

_PRIVATE_KEY_MARKER = "PRIVATE KEY"


def _private_key_pem() -> str:
    """Return private-key PEM text — really generated by openssl when available."""
    if shutil.which("openssl") is None:
        return _SYNTHETIC_PEM
    try:
        proc = subprocess.run(
            ["openssl", "genrsa", "2048"],  # noqa: S607 — resolved via PATH by design
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):  # pragma: no cover - env dependent
        return _SYNTHETIC_PEM
    if proc.returncode != 0 or _PRIVATE_KEY_MARKER not in proc.stdout:
        return _SYNTHETIC_PEM  # pragma: no cover - env dependent
    return proc.stdout


def _introspector(root: Path) -> SubprocessRepoIntrospector:
    """A REAL introspector (no fake runner) rooted at ``root``."""
    return SubprocessRepoIntrospector(PrivacyGuard(root))


def _plant_key(directory: Path, name: str) -> Path:
    """Write a private key at ``directory/name`` and assert it really is one."""
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / name
    target.write_text(_private_key_pem(), encoding="utf-8")
    # 🔴 The premise of every refusal below: without the fix this content WOULD leak.
    assert _PRIVATE_KEY_MARKER in target.read_text(encoding="utf-8")
    return target


@pytest.fixture
def secret_repo(tmp_path: Path) -> Path:
    """A tiny repo tree holding real key material plus ordinary, readable code."""
    _plant_key(tmp_path / ".secrets", "bob-ai-work.private-key.pem")
    (tmp_path / ".secrets" / "notes.txt").write_text("which key is which", encoding="utf-8")
    _plant_key(tmp_path / "keys", "service-account.pem")
    _plant_key(tmp_path / ".ssh", "id_ed25519")
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "mod.py").write_text(
        "def hello() -> str:\n    return 'hi'\n", encoding="utf-8"
    )
    return tmp_path


# --- 1. REFUSAL: the tools a model reaches cannot fetch key material ------------


@pytest.mark.parametrize(
    "target",
    [
        ".secrets/bob-ai-work.private-key.pem",  # the reproduced call, verbatim
        ".secrets/notes.txt",  # anything inside the secret store
        "keys/service-account.pem",  # a .pem outside .secrets
        ".ssh/id_ed25519",  # an ssh key with no suffix
    ],
)
@pytest.mark.asyncio
async def test_read_file_refuses_real_key_material_on_disk(
    secret_repo: Path, target: str
) -> None:
    intro = _introspector(secret_repo)

    with pytest.raises(DeniedPathError):
        await intro.read_file(target, max_lines=5)


@pytest.mark.asyncio
async def test_read_file_refuses_the_absolute_path_to_the_key_too(secret_repo: Path) -> None:
    # A model that spells the path absolutely gets the same refusal.
    absolute = str(secret_repo / ".secrets" / "bob-ai-work.private-key.pem")
    intro = _introspector(secret_repo)

    with pytest.raises(DeniedPathError):
        await intro.read_file(absolute, max_lines=5)


@pytest.mark.asyncio
async def test_list_dir_refuses_the_secrets_directory(secret_repo: Path) -> None:
    # The second reproduced call: ``list_dir('.secrets')`` enumerated both keys.
    intro = _introspector(secret_repo)

    with pytest.raises(DeniedPathError):
        await intro.list_dir(".secrets")


@pytest.mark.asyncio
async def test_find_file_does_not_enumerate_key_material(secret_repo: Path) -> None:
    # Otherwise the ``list_dir`` refusal is one glob away from being bypassed.
    intro = _introspector(secret_repo)

    pem_hits = await intro.find_file("*.pem")
    ssh_hits = await intro.find_file("id_*")

    assert "service-account.pem" not in pem_hits
    assert "bob-ai-work.private-key.pem" not in pem_hits
    assert "id_ed25519" not in ssh_hits


@pytest.mark.asyncio
async def test_key_material_is_denied_inside_the_real_repo_tree() -> None:
    """🔴 A key planted in the LIVE tree is refused — BOB-067's allowance does not win.

    The organisational half of the fix (the owner moving the keys out of the repo) must
    not be what protects us: the next secret to land in the tree will be a dump, a backup
    or another service's ``.pem``. So this test plants a real key inside the ACTUAL repo
    root, with the guard rooted exactly as production wires it, and requires refusal.
    """
    probe_dir = _REPO_ROOT / f".pytest-secret-probe-{os.getpid()}"
    try:
        _plant_key(probe_dir, "planted.pem")
        (probe_dir / "readme.md").write_text("ordinary note\n", encoding="utf-8")
        intro = _introspector(_REPO_ROOT)
        relative = f"{probe_dir.name}/planted.pem"

        with pytest.raises(DeniedPathError):
            await intro.read_file(relative, max_lines=5)

        # BOB-067 stays: the surrounding directory is still navigable, and the ordinary
        # file next to the key still reads. Only the key itself is out of reach.
        listing = await intro.list_dir(probe_dir.name)
        note = await intro.read_file(f"{probe_dir.name}/readme.md", max_lines=5)
        assert "readme.md" in listing
        assert "ordinary note" in note
    finally:
        shutil.rmtree(probe_dir, ignore_errors=True)


@pytest.mark.asyncio
async def test_the_live_secrets_directory_is_denied_if_it_still_exists() -> None:
    """The exact coordinator repro, run against the live config when it is still there.

    Skipped once the owner has moved the keys out (measure A) — the class-level proof is
    the planted-key test above, which never depends on those two files existing.
    """
    live = _REPO_ROOT / ".secrets"
    if not live.is_dir():
        pytest.skip(".secrets/ has been moved out of the repo (organisational measure A)")
    intro = _introspector(_REPO_ROOT)

    with pytest.raises(DeniedPathError):
        await intro.list_dir(".secrets")
    for key in sorted(live.glob("*.pem")):
        with pytest.raises(DeniedPathError):
            await intro.read_file(f".secrets/{key.name}", max_lines=5)


# --- 2. BACKSTOP: when the guard misses, sanitize must still save us ------------


@pytest.mark.asyncio
async def test_key_material_under_an_ordinary_name_is_read_but_redacted(
    tmp_path: Path,
) -> None:
    # 🔴 The independent second layer: a shape-based path rule can always be dodged (a
    # key pasted into a note, a backup named ``.txt``), so the text that leaves the
    # machine is scrubbed as well. Here the guard deliberately ALLOWS the read.
    note = tmp_path / "docs" / "notes.md"
    note.parent.mkdir()
    note.write_text(
        "onboarding notes\n"
        f"{_private_key_pem()}"
        "push with ghs_16CharsAndMoreFakeInstallationTok\n"
        "app jwt: eyJhbGciOiJSUzI1NiJ9.eyJpc3MiOiIxMjMifQ.ZmFrZXNpZ25hdHVyZWZha2U\n",
        encoding="utf-8",
    )
    intro = _introspector(tmp_path)

    out = await intro.read_file("docs/notes.md", max_lines=200)

    assert _PRIVATE_KEY_MARKER not in out
    assert "ghs_16CharsAndMoreFakeInstallationTok" not in out
    assert "eyJpc3MiOiIxMjMifQ" not in out
    assert "REDACTED" in out
    assert "onboarding notes" in out  # the surrounding prose survives


@pytest.mark.asyncio
async def test_a_truncated_key_read_is_redacted_too(tmp_path: Path) -> None:
    # The reproduced call used ``max_lines=5``, so the closing ``-----END-----`` marker
    # never arrived — the shape a block-anchored pattern would have missed.
    note = tmp_path / "dump.md"
    note.write_text(_private_key_pem(), encoding="utf-8")
    intro = _introspector(tmp_path)

    out = await intro.read_file("dump.md", max_lines=5)

    assert _PRIVATE_KEY_MARKER not in out
    assert "REDACTED" in out


# --- 3. BOB-067: full-repo navigation is untouched ------------------------------


@pytest.mark.asyncio
async def test_ordinary_navigation_still_works_in_the_same_tree(
    secret_repo: Path,
) -> None:
    intro = _introspector(secret_repo)

    code = await intro.read_file("src/mod.py", max_lines=50)
    listing = await intro.list_dir("src")
    root_listing = await intro.list_dir(".")
    hits = await intro.find_file("*.py")

    assert "def hello()" in code
    assert "mod.py" in listing
    assert "src/" in root_listing
    assert "src/mod.py" in hits


@pytest.mark.asyncio
async def test_escape_past_the_repo_is_still_denied(secret_repo: Path) -> None:
    intro = _introspector(secret_repo)

    with pytest.raises(DeniedPathError):
        await intro.read_file("../outside.txt", max_lines=5)


