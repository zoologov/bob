"""Место реплики — недавняя нить, показанная Бобу с пометкой, ГДЕ что прозвучало (C3).

Одна ответственность: **показать недавнюю нить так, чтобы каждая реплика несла место, в
котором она была сказана** — и ничего больше (ни отбора, ни порядка, ни содержания).

🔴 Живой дефект (эпизоды 3331/3333, 2026-08-05). Owner в ЛИЧКЕ просит «расскажи в
группе»; Боб отвечает шуткой в личку, а на повтор просьбы говорит: «я же только что
рассказал ГРУППЕ». Он не соврал — он был уверен, и поэтому НЕ позвал ``send_to_chat``.
Корень: нить темы приезжала в промпт общим списком реплик БЕЗ пометки места, а личка
появилась в BOB-082 и её реплики (``visibility='owner_private'``) идут в ту же нить
наравне с групповыми. Провенанс среза C1 закрыл ПРИПОМНЕННОЕ, но на коротком горизонте
(«только что») доминирует именно нить, и она шла мимо.

🔴 Почему место едет НА КАЖДОЙ реплике, а не одной директивой на весь блок (как в C1).
Припомненное — множество, о котором честно сказать «всё это было в личке». Нить — почти
всегда СМЕСЬ (личка и комната вперемешку по времени), и единственное, что честно сказать
о смеси одной строкой, — «где-то как-то, не угадывай». Это не даёт Бобу ЗНАНИЯ, а беада
требует ровно знания: он один разум, видит обе стороны и должен лишь помнить, где что
было. Поэтому форма другая — но ось, сигнал и правила те же, что в C1: та же метка
``visibility`` со стороны записи, тот же флаг ``memory.origin_provenance``, то же правило
«неизвестное место молчит». Второй механизм не заводится: директива C1 продолжает отвечать
за припомненное, этот модуль — за нить.

🔴 Словарь мест берётся из :mod:`bob.kernel.visibility` — общей нейтральной поверхности,
а не новым зеркальным литералом (в отличие от вынужденного зеркала в ``personality.voice``,
которому нельзя импортировать ``social``): у ``conversation`` дорога в ядро уже есть, а
лишняя копия слова — лишний источник расхождения.

🔴 Неизвестное место МОЛЧИТ. ``visibility IS NULL`` (строка до миграции) и незнакомое
слово — это «не знаю где», а не «сказано при всех»: гейт разглашения читает ``NULL`` как
публичный (fail-open единой памяти BOB-051), но превращать молчание в утверждение о месте
и есть тот самый дефект. Нить, где ни одна реплика не несёт известного места, выглядит
ровно как раньше — без пометок и без легенды.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from bob.kernel.visibility import VISIBILITY_OWNER_PRIVATE, VISIBILITY_PUBLIC

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

__all__ = [
    "PLACE_PRIVATE_MARK",
    "PLACE_ROOM_MARK",
    "THREAD_PLACES_LEGEND",
    "thread_block",
]

# Заголовок блока нити в контексте ответа — ровно тот, что был до C3: выключенный путь
# обязан совпадать с прежним байт-в-байт.
_THREAD_HEADING = "Recent conversation:"

# Пометки места. Кириллические похожие буквы в русских литералах — намеренно.
PLACE_PRIVATE_MARK = "[в личке]"
PLACE_ROOM_MARK = "[в общем чате, при всех]"

# Легенда: что означают пометки и что с ними делать. Живёт ВПЛОТНУЮ к материалу (а не
# отдельной директивой), потому что объясняет именно эти квадратные скобки — и вместе с
# ними исчезает, когда ни одного места не известно. Последнее предложение — прямой
# антидот живого дефекта: просьбу «скажи в группе» Боб счёл выполненной, потому что
# сказал это в личке.
THREAD_PLACES_LEGEND = (
    "(в квадратных скобках — ГДЕ прозвучала реплика: «в личке» — наедине, только между "
    "вами; «в общем чате» — при всех. Без пометки место неизвестно — не называй его "
    "наугад. Сказанное в личке не выдавай за сказанное при всех и наоборот: если тебя "
    "просят сказать что-то в общий чат, а говорили вы об этом в личке, значит в общий "
    "чат это ещё не попадало.)"
)

_PLACE_MARKS = {
    VISIBILITY_OWNER_PRIVATE: PLACE_PRIVATE_MARK,
    VISIBILITY_PUBLIC: PLACE_ROOM_MARK,
}


def thread_block(
    history: Sequence[Mapping[str, object]], *, mark_places: bool = False
) -> str:
    """Блок недавней нити для контекста ответа; ``""`` — реплик нет (BOB-090.C3).

    Реплики отдаются в том же порядке и с тем же содержимым, что и раньше; при
    ``mark_places`` каждая получает пометку места (:data:`PLACE_PRIVATE_MARK` /
    :data:`PLACE_ROOM_MARK`), а блок — объясняющую их легенду. Реплика с НЕИЗВЕСТНЫМ
    местом остаётся без пометки, и нить, где неизвестны все, выглядит ровно как при
    выключенном флаге — молчание о месте честно, выдуманное место и есть дефект.

    Чистая и детерминированная: та же нить → тот же блок. Ничего не фильтруется и не
    переставляется — место это СИГНАЛ для суждения, а не отбор (сквозная память BOB-082).
    """
    placed = [
        (_place_mark(item) if mark_places else "", str(item["content"]))
        for item in history
        if item.get("content")
    ]
    if not placed:
        return ""
    turns = [f"{mark} {said}" if mark else said for mark, said in placed]
    heading = (
        f"{_THREAD_HEADING}\n{THREAD_PLACES_LEGEND}"
        if any(mark for mark, _ in placed)
        else _THREAD_HEADING
    )
    return "\n".join([heading, *turns])


def _place_mark(item: Mapping[str, object]) -> str:
    """Пометка места этой реплики, или ``""`` — место неизвестно."""
    value = item.get("visibility")
    if not isinstance(value, str):
        return ""
    return _PLACE_MARKS.get(value.strip().casefold(), "")
