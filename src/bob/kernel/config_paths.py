"""Как понимать ПУТЬ, приехавший из конфига — одно правило на весь проект (bob-a6b.15).

ОДНА ответственность: превратить значение конфига в путь, не соврав про его происхождение.
Три ветки, и каждая обязана быть именно такой:

* АБСОЛЮТНОЕ значение уважается КАК ЕСТЬ. 🔴 Приклеить к нему корень проекта — тот самый
  P0 bob-a6b.15: owner вынес приватные ключи из дерева репозитория (``~/.config/bob/
  secrets/``, 0700/0600 — место, куда не достаёт ни ``read_code``, ни git), прописал
  абсолютные пути, и подпись App-JWT умерла на
  ``/Users/o/bob//Users/o/.config/bob/secrets/bob-ai-work.private-key.pem``. То есть
  ЕДИНСТВЕННАЯ безопасная конфигурация оказалась невыразимой, а прежние смоуки проходили
  ровно потому, что путь был относительным и небезопасным.
* Значение с ``~`` раскрывается по ДОМАШНЕМУ каталогу. Для :mod:`pathlib` тильда не
  абсолютна, поэтому без этой ветки ``~/.config/bob/secrets/work.pem`` склеился бы с корнем
  проекта (``<repo>/~/.config/...``) — тот же дефект, только другой формой записи. Это
  единственное место правила, которое смотрит в окружение (``HOME``), и файловую систему
  оно всё равно не трогает.
* ОТНОСИТЕЛЬНОЕ значение привязывается к КОРНЮ ПРОЕКТА, а не к текущему каталогу процесса.
  🔴 Урок BOB-087.D5b: разрешение от ``cwd`` зелено в тестах (они и так стоят в корне) и
  мертво в проде, где процесс запущен откуда угодно.

О существовании пути правило не судит и на диск не смотрит: оно применяется и к файлу,
который ещё только будет создан (каталог клонов, файлы окружения спавна).

🔴 ЧЕСТНО ПРО ПЕРВУЮ ВЕТКУ. Через :mod:`pathlib` склеить нельзя в принципе: ``root / path``
с абсолютным правым операндом возвращает правый операнд (проверено саботажем — замена
правила на безусловное ``root / path`` не роняет ни один тест). Живая склейка приезжала из
ФОРМАТИРОВАНИЯ строк (``f"{root}/{value}"`` — отсюда двойной слэш в
``/Users/o/bob//Users/o/...``) и из тильды, которая для pathlib не абсолютна. Условие
оставлено ЯВНЫМ не как страховка от pathlib, а как формулировка правила: читающий видит,
что абсолютное значение уважается, и не «поправит» его конкатенацией.

🔴 ПОЧЕМУ ПРАВИЛО ЖИВЁТ В ЯДРЕ. Его спрашивают и домен (``bob.identity.credentials`` —
путь к приватному ключу принципала), и композиция (``bob.runtime.wiring.coding`` —
``coder.clone_root``). Домен не имеет права импортировать композицию, а вторая копия
однажды разъедется с первой — и разъедется молча, потому что «путь не тот» видно только в
проде. Тот же довод, по которому в ядре живёт :func:`bob.kernel.visibility.
strictest_visibility`: общее слово не стоит ребра между модулями.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["under_root"]


def under_root(value: str | Path, *, root: Path) -> Path:
    """Вернуть путь ``value``, привязанный к ``root`` только если он относительный."""
    path = Path(value).expanduser()
    return path if path.is_absolute() else root / path
