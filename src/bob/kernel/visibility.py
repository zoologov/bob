"""Общий словарь оси ПРИВАТНОСТИ + правило наследования метки — bob-g7t.

Метка видимости (``public`` / ``owner_private``) — это РАЗРЕШЕНИЕ, записанное рядом с
воспоминанием (BOB-066 2.6). Такт разглашения (:mod:`bob.social.disclosure`) читает её,
чтобы решить, что Боб выносит по своей инициативе; гейт переноса (BOB-090.B) — чтобы
решить, что уезжает в публичный чат. Оба читают метку ИСХОДНОЙ записи.

Этот модуль отвечает за один вопрос: **какую метку носит ПРОИЗВОДНАЯ запись, собранная
из нескольких источников** (сегодня — дайджест консолидации, :mod:`bob.memory.usecases.
consolidate_memory`). Ответ — :func:`strictest_visibility`: самую строгую из меток
источников.

🔴 Почему слово живёт ЗДЕСЬ, а не в ``social``. Правило нужно ``memory`` (она мнёт
производные записи) и совпадает по словарю с ``social`` (она судит такт). Прямой импорт
``memory → social`` замыкает цикл узлов (``no-dependency-cycles``, проверено
``beadloom lint --strict``), ровно как в bob-abk.32 с ``WORK_EVENT_TYPE``. Ядро —
нейтральная поверхность, которую импортируют все, поэтому общее слово не стоит ребра.

🔴 ОСТАТОК: :mod:`bob.social.disclosure` пока объявляет СВОИ копии этих двух литералов —
перенаправить его сюда в этой беаде было нельзя (``social/**`` был живой зоной
параллельного агента). До тех пор расхождение стережёт тест
``tests/domain/kernel/test_visibility.py::test_the_kernel_words_do_not_drift_from_the_social_ones``.

Значения ПЕРСИСТЯТСЯ в ``episodic_log.visibility`` / ``semantic_memory.visibility`` —
менять их значит переписывать историю, поэтому они стабильны.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable

__all__ = [
    "VISIBILITY_OWNER_PRIVATE",
    "VISIBILITY_PUBLIC",
    "is_owner_private",
    "strictest_visibility",
]

# Две метки провенанса, которые может нести воспоминание. Хранятся в nullable-колонке,
# и ``NULL`` читается как PUBLIC — так единая память BOB-051 и любая до-миграционная
# строка остаются доступными всем, а придерживается только то, что Боб пометил сам.
VISIBILITY_PUBLIC = "public"
VISIBILITY_OWNER_PRIVATE = "owner_private"


def is_owner_private(visibility: str | None) -> bool:
    """Приватна ли запись с такой меткой — ЕДИНСТВЕННОЕ определение «приватного».

    Приватной считается ровно метка ``owner_private`` (регистр и пробелы не важны:
    иначе разница в написании отмывала бы разрешение). ``None`` (legacy-строка) и любое
    НЕИЗВЕСТНОЕ слово читаются как публичные — незнакомому слову не позволено молча
    прятать публичную память; ровно так же трактует их
    :func:`bob.social.disclosure.may_surface`. Чистая и детерминированная.
    """
    return (visibility or "").strip().casefold() == VISIBILITY_OWNER_PRIVATE


def strictest_visibility(labels: Iterable[str | None]) -> str:
    """Самая строгая метка среди ``labels`` — метка производной записи (bob-g7t).

    Производная запись (дайджест) содержит СОДЕРЖИМОЕ всех своих источников, поэтому
    она обязана нести самое строгое из их разрешений: хоть один ``owner_private`` среди
    источников — вся производная приватна.

    🔴 Почему именно «самая строгая», а не «большинство» и не «последняя». Метка — это
    разрешение на содержимое, а не свойство большинства и не свойство последней строки.
    Одно приватное предложение внутри дайджеста остаётся приватным независимо от того,
    сколько публичных предложений его окружает («большинство» отмыло бы его при 49
    публичных источниках из 50) и в каком порядке они попали в окно («последняя» отмыла
    бы его при любом публичном хвосте). Правило монотонно: добавление источника может
    только УЖЕСТОЧИТЬ метку, никогда не ослабить, — поэтому свернуть приватное «нечаянно
    в публичное» структурно невозможно.

    ПУСТОЙ набор источников даёт ``owner_private``: «публично» — это утверждение, и
    подкрепить его нечем, когда предъявить нечего (INV-8, сомнение придерживает, а не
    разглашает). На пути записи это недостижимо (дайджест без источников не рождается);
    на пути починки данных это ровно случай «провенанс не разрешился» — и он получает
    строгий ответ, а не публичный по умолчанию.

    Чистая и детерминированная: одни и те же метки → тот же ответ.
    """
    labels = list(labels)
    if not labels:
        return VISIBILITY_OWNER_PRIVATE
    if any(is_owner_private(label) for label in labels):
        return VISIBILITY_OWNER_PRIVATE
    return VISIBILITY_PUBLIC
