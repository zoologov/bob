"""restart_voice — голос Боба, когда он уходит на обновление и когда возвращается (BOB-094 срез 1).

🔴 ГРАНИЦА КАНОНА (BOB-090.D). Рестарт по деплою — это НЕ строка деплой-скрипта и не
системный нотис GUPPI: это ГОЛОС самого Боба. Перед остановкой он по-человечески
предупреждает «ухожу обновиться, скоро вернусь», а после старта говорит «вернулся,
обновился». Отправка и решение «а был ли это апдейт» живут снаружи (runtime-хук +
маркер в ``kv``); здесь — только ЧТО именно Боб говорит.

ОДНА ответственность: по моменту рестарта (:class:`RestartMoment` — уходит / вернулся)
выбрать ОДНУ из нескольких ЖИВЫХ, заранее написанных формулировок от первого лица.
Образец — :mod:`bob.proactivity.rule_voice` (BOB-096): не шаблон со слотами, куда
что-то подставляется (это и читалось owner'ом как «скриптовано»), а веер готовых
человеческих реплик, из которого выбор лишь ВЫБИРАЕТ, ничего не собирая по кускам.

Детерминированно и без источников недетерминизма. ``random`` и время в этом окружении
запрещены (и всё равно сделали бы реплику невоспроизводимой в тесте), поэтому вариант
выбирается по устойчивому хешу МАРКЕРА рестарта (тот же маркер, что отличает
апдейт-остановку от падения) — так уход и следующее возвращение звучат по-разному от
раза к разу, но детерминированно для данного запуска. Никакого LLM-вызова, никакого
I/O: одинаковый вход → одинаковый результат.
"""

from __future__ import annotations

import hashlib
from enum import Enum

__all__ = ["RestartMoment", "restart_voice"]


class RestartMoment(Enum):
    """Момент рестарта, о котором говорит Боб: уходит на обновление / вернулся после него."""

    LEAVING = "leaving"
    RETURNED = "returned"


# Уход на обновление: короткое человеческое предупреждение перед остановкой. Тон —
# спокойный и бытовой, не «система уведомляет о плановом обслуживании». Каждая реплика
# самодостаточна: «ухожу» + «ненадолго» + «вернусь» — чтобы owner не гадал, надолго ли.
_LEAVING = (
    "Ухожу на пару минут — накатываю обновление. Скоро вернусь 🙂",
    "Так, меня немного обновляют. Отойду ненадолго и вернусь.",
    "Обновляюсь — пропаду на минутку, не теряйте. Вернусь.",
    "Мне тут подвезли апдейт, ставлю его. Отлучусь ненадолго 🙂",
    "Переезжаю на свежую версию — на минуту исчезну и снова буду.",
)

# Возвращение после обновления: Боб сам отмечает, что вернулся и что стал новее. Не
# рапорт «сервис восстановлен», а живое «я снова тут».
_RETURNED = (
    "И снова я — обновился и вернулся 🙂",
    "Всё, я на месте. Обновился, продолжаем.",
    "Вернулся уже посвежевшим — обновление встало. Что нового?",
    "Готово, я снова с вами — с новой версией на борту.",
    "Обновился и вернулся. Соскучиться не успели? 🙂",
)


def restart_voice(moment: RestartMoment, *, marker: str) -> str:
    """Собрать то, что Боб ГОВОРИТ на рестарте: уход на обновление или возвращение.

    ``moment`` выбирает веер (уходит / вернулся); ``marker`` — устойчивый ключ
    рестарта (тот же, что в ``kv`` отличает апдейт-остановку от падения) —
    детерминированно выбирает ОДНУ реплику из веера. Тотально: любой ``marker``,
    включая пустой, даёт валидную непустую реплику (хеш определён на любой строке).
    """
    variants = _RETURNED if moment is RestartMoment.RETURNED else _LEAVING
    return variants[_index_for(marker, len(variants))]


def _index_for(marker: str, span: int) -> int:
    """Устойчивый индекс варианта по маркеру: детерминированно, без ``random``/времени.

    Хеш берётся от БАЙТОВ маркера (SHA-256 — устойчив между запусками, в отличие от
    ``hash()`` с рандомизацией соли), поэтому один и тот же маркер всегда выбирает одну
    и ту же реплику, а разные маркеры расходятся по вееру.
    """
    digest = hashlib.sha256(marker.encode("utf-8")).digest()
    return digest[0] % span
