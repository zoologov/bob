"""rule_voice — голос Боба, когда он предлагает поправить САМОГО СЕБЯ (BOB-096 срез 5).

Живой симптом (owner, 12 августа 2026): «Заметил за собой: Боб замечает, что его
поведение часто повторяется**..** Предлагаю: **.** Включить? (/rule approve rule-…)».
Приговор владельца — «выглядит очень скриптовано, а не человечно», и он про
конструкцию, а не про формулировку: реплика собиралась строковым шаблоном с тремя
слотами, куда ДОСЛОВНО подставлялся вывод детектора. Отсюда все швы разом — Боб говорит
о себе в третьем лице (так его назвала модель), пустой слот даёт двойную точку, а
идентификатор правила стоит внутри фразы.

Лечение — то же разделение ролей, что в :mod:`bob.social.permission.request_voice`, а не
перевод строки и не генерация:

* **вердикт детектора остаётся внутренним** — ``observation`` / ``adjustment`` /
  ``evidence`` не произносятся вовсе; сюда они и НЕ ПЕРЕДАЮТСЯ (билдер их не принимает),
  поэтому текст модели не может стать телом фразы ни при какой доработке вызывающего;
* **что именно Боб заметил, говорит сам Боб** — это готовые формулировки от первого
  лица, а ВЫБИРАЕТ из них ``lever`` (жёсткий allowlist :class:`Lever` — единственное, что
  в вердикте по-настоящему определяет, о какой своей черте он говорит);
* **насколько сильно** — полоса по ``magnitude``: «чуть» / «заметно» / «сильно»;
* **пустых слотов нет по конструкции** — фраза склеена из непустых констант, поэтому ни
  ``«..»``, ни ``«Предлагаю: .»`` не рождаются даже на странном входе (вырожденное
  предложение до сюда и не доходит — срез 2, — но форма от этого не зависит).

🔴 ГРАНИЦА КАНОНА внутри одного сообщения (BOB-090.D, :mod:`bob.coding.speaker`).
Предложение изменить себя — это ГОЛОС БОБА: его наблюдение о себе и просьба к человеку
(в терминах :class:`~bob.coding.speaker.MessageKind` — живое, а не механика). А команда
``/rule approve <id>`` — механика, и она УЖЕ принадлежит GUPPI: команды ``/rule`` и
``/rules`` обрабатывает :class:`~bob.infrastructure.telegram.guppi.GuppiHandler` и
отвечает на них своим ботом. Разводить одно предложение на два бота (речь от Боба,
идентификатор от GUPPI) для владельца хуже, а не лучше: два сообщения пришлось бы
сопоставлять глазами, и это потребовало бы второго канала в доставке (срез 1, чужая
зона). Поэтому компромисс назван прямо: сообщение ОДНО и уходит боту Боба, но
идентификатор не произносится — он вынесен служебной сноской отдельной строкой, голой
командой без слов вокруг. Боб говорит; механика лежит рядом подписью, а не внутри речи.
Подробности правила владелец видит там же, где механика, — в списке ``/rules`` у GUPPI.

Чисто и детерминированно, по образцу :mod:`bob.social.permission.request_voice`: никакого
LLM-вызова на реплику, никакого I/O, одинаковый вход → одинаковый результат.
"""

from __future__ import annotations

from dataclasses import dataclass

from bob.proactivity.self_improvement import Lever

__all__ = ["proposal_message", "proposal_speech"]


@dataclass(frozen=True, slots=True)
class _Wording:
    """Три части реплики: что Боб за собой заметил, что хочет сделать и сам вопрос."""

    notice: str
    intent: str
    question: str


# Тон: направление поправки (теплее / суше) живёт в его собственной заметке, которую он
# потом держит в голосе, поэтому вслух он честно говорит «не тем тоном», не выдумывая
# сторону.
_TONE = _Wording(
    notice="Кажется, я говорю не тем тоном, каким хотел бы",
    intent="поправить тон",
    question="Попробуем?",
)
# Длина: направление у рычага одно и зафиксировано применением — короче, никогда длиннее.
_LENGTH = _Wording(
    notice="Ловлю себя на том, что отвечаю длиннее, чем нужно",
    intent="ужаться",
    question="Стоит?",
)
# Проактивность: байес поднимает его порыв заговорить — то есть «чаще сам», не наоборот.
_PROACTIVITY = _Wording(
    notice="Заметил, что всё жду, когда меня позовут, вместо того чтобы заговорить самому",
    intent="осмелеть",
    question="Дашь добро?",
)
# Адресность: байес поднимает интерес, с которым он читает разговор рядом.
_ADDRESSIVITY = _Wording(
    notice="Замечаю, что пропускаю мимо ушей разговоры, в которых мне есть что сказать",
    intent="прибавить внимания к тому, что говорят рядом",
    question="Не против?",
)
# Юмор: как и с тоном, сторону поправки Боб вслух не выдумывает.
_HUMOR = _Wording(
    notice="С шутками я, по-моему, попадаю не всегда",
    intent="подкрутить чувство юмора",
    question="Попробовать?",
)
# Рычаг, которого Боб не знает (allowlist такого не даёт, но ядро обязано быть тотальным):
# предложение остаётся предложением, без домыслов о том, что именно он заметил.
_UNSPECIFIED = _Wording(
    notice="Заметил за собой кое-что, что стоило бы поправить",
    intent="подстроиться",
    question="Попробуем?",
)

# Полосы величины наклона. Нижние границы включительны, диапазон рычага — ``[0, 1]``.
# Выбраны ВНУТРИ реально достижимого: живой потолок предложения (``max_magnitude``) —
# 0.3, поэтому «чуть» и «заметно» обязаны различаться уже на нём, иначе полоса была бы
# мёртвой. Верхняя полоса живёт не «на вырост»: потолок — ключ конфига, владелец вправе
# его поднять, и наклон в половину шкалы называть «чуть» было бы неправдой.
_NOTICEABLE_TILT = 0.15
_STRONG_TILT = 0.5

_SLIGHTLY = "чуть"
_NOTICEABLY = "заметно"
_STRONGLY = "сильно"

# Служебная сноска: голая команда владельцу, чтобы включить правило. Механика (GUPPI'ных
# ``/rule`` / ``/rules``), поэтому она вынесена ИЗ речи отдельной строкой и набрана
# моноширинно — её копируют, а не читают как слова Боба.
_APPROVE_COMMAND = "/rule approve"
_FOOTNOTE_GAP = "\n\n"


def proposal_speech(*, lever: Lever, magnitude: float) -> str:
    """Собрать то, что Боб ГОВОРИТ, предлагая поправить себя: наблюдение, намерение, вопрос.

    ``lever`` и ``magnitude`` — ВНУТРЕННИЙ вердикт детектора: они лишь выбирают готовые
    слова Боба и в текст не попадают. Сырой текст детектора сюда не передаётся вовсе (см.
    модульный докстринг), поэтому реплика не может ни заговорить о Бобе в третьем лице,
    ни развалиться на пустом слоте.
    """
    wording = _wording_for(lever)
    return f"{wording.notice}. Хочу {_degree_for(magnitude)} {wording.intent}. {wording.question}"


def proposal_message(*, lever: Lever, magnitude: float, rule_id: str) -> str:
    """Собрать сообщение владельцу: слова Боба плюс служебная сноска с командой.

    Идентификатор правила — механика, поэтому он не произносится, а стоит отдельной
    строкой голой командой (см. модульный докстринг про границу канона). Пустой
    идентификатор командой не становится: неисполнимой сноски не остаётся вовсе, и
    владелец получает ровно то, что Боб сказал бы и без всякой механики.
    """
    speech = proposal_speech(lever=lever, magnitude=magnitude)
    identifier = rule_id.strip()
    if not identifier:
        return speech
    return f"{speech}{_FOOTNOTE_GAP}`{_APPROVE_COMMAND} {identifier}`"


def _wording_for(lever: Lever) -> _Wording:
    """Выбрать слова Боба по рычагу вердикта (незнакомый рычаг — общий случай).

    Рычаги сравниваются ПОЭЛЕМЕНТНО в теле функции, а не таблицей-константой наверху
    файла: подмена любой ветки тогда — видимый мутант, и гейт измеряет саму политику, а
    не форму записи (MUTATION.md, §«Порог и честность»).
    """
    if lever is Lever.TONE:
        return _TONE
    if lever is Lever.LENGTH:
        return _LENGTH
    if lever is Lever.PROACTIVITY:
        return _PROACTIVITY
    if lever is Lever.ADDRESSIVITY_BIAS:
        return _ADDRESSIVITY
    if lever is Lever.HUMOR:
        return _HUMOR
    return _UNSPECIFIED


def _degree_for(magnitude: float) -> str:
    """Назвать величину наклона словом Боба: «чуть» / «заметно» / «сильно».

    Тотально по построению: величина ниже первой полосы (в том числе нулевая,
    отрицательная или нечисловая — такие сюда не доходят, но форма от этого не зависит)
    звучит как «чуть», то есть фраза остаётся фразой на любом входе.
    """
    if magnitude >= _STRONG_TILT:
        return _STRONGLY
    if magnitude >= _NOTICEABLE_TILT:
        return _NOTICEABLY
    return _SLIGHTLY
