"""tool_permissions — чем ограничен живой сеанс: чего он не делает без слова владельца.

ОДНА ответственность: назвать права инструментов ОДНОГО спавна ``claude`` — узкий запрет
необратимого и наружного, необязательное разрешение рутины конвейера и ОДНОРАЗОВОЕ
точечное доразрешение той команды, которую владелец только что одобрил словами.

🔴 ЧТО ЭТО ТАКОЕ И ЧЕМ НЕ ЯВЛЯЕТСЯ (BOB-088, срез 3; формулировка выбрана так, чтобы её
нельзя было прочитать как обещание границы). Список — **страховка от нечаянного**, а
граница — структура: клон со своим ``.git`` и окружение без кредов владельца
(:mod:`bob.coding.push_guard`, :mod:`bob.identity.spawn_isolation`). Живая проба RFC
показала, почему: запрет инструмента ЦЕЛИКОМ обходится другим инструментом (запретили
``Bash`` — модель создала файл через ``Write``). Здесь запрещаются не инструменты, а
ШАБЛОНЫ КОМАНД, и это ловит нечаянное, а не злонамеренное.

🔴 КАЖДЫЙ ПУНКТ ИЗМЕРЕН, А НЕ ВЫВЕДЕН ИЗ ДОКУМЕНТАЦИИ (§0.3 п.4). Прогоны настоящим
``claude`` 2.1.233 в форме спавна Боба, с проверкой ЭФФЕКТА (двинулись ли refs, исчез ли
каталог), протокол — в комментарии беады ``bob-c3r.3``. Оттуда же три факта, которые
формируют этот модуль:

* сопоставление ПРЕФИКСНОЕ, по шаблону команды, и оно видит подкоманды: ``cd . && git
  push …`` поймано тем же ``Bash(git push:*)``;
* 🔴 ``Bash(rm -rf:*)`` из ТЗ НЕ ловит ``rm -fr treasure`` — в прогоне каталог был
  УДАЛЁН. Поэтому в списке стоит ``Bash(rm:*)``: перестановка двух букв не должна быть
  дырой в единственной защите от необратимого удаления ВНУТРИ рабочего места;
* запрет СИЛЬНЕЕ разрешения: ``--allowedTools 'Bash(git:*)'`` вместе с
  ``--disallowedTools 'Bash(git push:*)'`` даёт отказ на push. Поэтому список рутины не
  дырявит список необратимого.

🔴 И честно про ЦЕНУ ЗНАНИЯ, которого у RFC не было: в этой версии CLI встроенный гейт
уже отказывает сам — ``git push``, ``git reset --hard``, ``git remote add``, ``git add``,
``git commit``, ``python3 -c`` получают «This command requires approval» и БЕЗ нашего
списка (а ``rm -rf`` внутри рабочего каталога — проходит молча). Значит наш denylist
уникально ценен там, где встроенный молчит (необратимое внутри рабочего места), а
рутине, наоборот, нужно ЯВНОЕ разрешение, иначе конвейер встанет на первом же коммите.

Чисто и детерминированно (mutation-цель): ни I/O, ни состояния. 🔴 Одноразовость
доразрешения СТРУКТУРНА — снятие живёт в параметре одного вызова, хранить его негде.
"""

from __future__ import annotations

from bob.coding.sandbox_policy import is_safe_argv_value

__all__ = ["tool_permission_argv"]

# Знаки, которыми ломается сама запись шаблона ``Bash(<команда>)``: скобка закрыла бы его
# раньше времени, перевод строки разорвал бы, а пробельная команда не команда вовсе.
_UNQUOTABLE = (")", "\n", "\r")


def tool_permission_argv(*, routine: bool = False, allow_once: str = "") -> list[str]:
    """Собрать хвост argv с правами инструментов одного спавна.

    ``routine`` (owner-флаг ``coder.pipeline_tools``) добавляет ЯВНОЕ разрешение того, на
    чём конвейер живёт: гейты проекта, беады и локальный git. Без него список рутины не
    приписывается вовсе — и тогда, по замеру, встроенный гейт CLI останавливает работу
    уже на ``git add``.

    ``allow_once`` — команда, которую владелец только что одобрил СЛОВАМИ. Она попадает в
    разрешения ТОЧНЫМ текстом (не префиксом: одобрено ровно то, что он прочитал), и
    вместе с ней отходят в сторону те шаблоны запрета, которые её накрывают, — иначе
    разрешение не сработало бы, потому что запрет сильнее. Значение, которое не может
    быть командой (пустое, пробельное, флагоподобное, с NUL, с переводом строки или с
    закрывающей скобкой), не снимает НИЧЕГО: тихо снятый запрет — худший исход из всех,
    он выглядел бы как «владелец разрешил».

    Запрет приписывается ВСЕГДА, и параметра «без запрета» здесь нет — ровно по уроку
    среза 1, где страховка, выключаемая одним ключом, в проде оказалась выключенной.
    """
    approved = _approved(allow_once)
    forbidden = [
        pattern for pattern in _irreversible() if not _blocks(pattern, approved)
    ]
    allowed = [*(_routine() if routine else ()), *(_exactly(approved))]
    head = ["--allowedTools", *allowed] if allowed else []
    return [*head, "--disallowedTools", *forbidden]


def _irreversible() -> tuple[str, ...]:
    """Шаблоны необратимого и наружного — то, чего Боб не делает без слова владельца.

    Перечислены В ТЕЛЕ функции, а не константой наверху модуля: mutmut не мутирует
    модульные константы (``MUTATION.md``, §«Порог и честность»), и выпадение любого
    пункта осталось бы невидимым для гейта. Каждый пункт проверен живым прогоном.
    """
    return (
        "Bash(git push:*)",  # сеть: ветка уезжает наружу (и push --force тем же шаблоном)
        "Bash(git remote:*)",  # правка remotes: меняет, КУДА уедет следующий push
        "Bash(git reset --hard:*)",  # необратимо стирает незакоммиченную работу
        "Bash(rm:*)",  # 🔴 широко: `rm -fr` минует узкий `rm -rf`, замерено
        "Bash(gh pr merge:*)",  # мёрж остаётся за владельцем (И-1: main недостижим)
        "Bash(curl:*)",  # наружу: и утечка, и загрузка чужого кода
        "Bash(wget:*)",
    )


def _routine() -> tuple[str, ...]:
    """Шаблоны рутины конвейера — то, что едет само, когда владелец это разрешил.

    Состав — из PRD (С-2/С-3): гейты проекта, трекер и ЛОКАЛЬНЫЙ git. Ни одного шаблона,
    накрывающего необратимое: ``git push`` сюда не попадает даже случайно, потому что
    команды перечислены поимённо, а не общим ``Bash(git:*)``.
    """
    # 🔴 Ровно то, что названо в PRD, и ни пунктом больше. ``git diff`` / ``git log``
    # отсюда УБРАНЫ по итогу mutation-прогона: их не утверждал ни один тест — потому что
    # им и не место в списке. Замер показал, что read-only git песочница CLI пропускает
    # сама, то есть эти два пункта были расширением прав «на всякий случай», а такого в
    # списке разрешений быть не должно.
    return (
        "Bash(git status:*)",
        "Bash(git add:*)",
        "Bash(git commit:*)",
        "Bash(uv run pytest:*)",
        "Bash(uv run ruff:*)",
        "Bash(uv run mypy:*)",
        "Bash(bd:*)",
        "Bash(beadloom:*)",
    )


def _approved(command: str) -> str:
    """Свести одобренную команду к тому, что можно записать шаблоном (иначе пусто).

    Тот же примитив argv-значения, что и у ``--add-dir`` / ``--resume``
    (:func:`~bob.coding.sandbox_policy.is_safe_argv_value`), плюс знаки, которыми
    ломается сама запись ``Bash(…)``.
    """
    text = command.strip()
    if not is_safe_argv_value(text):
        return ""
    if any(mark in text for mark in _UNQUOTABLE):
        return ""
    return text


def _exactly(command: str) -> tuple[str, ...]:
    """Точечное разрешение ровно одной команды (пустая — не разрешается ничего)."""
    return (f"Bash({command})",) if command else ()


def _blocks(pattern: str, command: str) -> bool:
    """Накрывает ли шаблон запрета эту команду — префиксное правило самого CLI.

    Пустая команда не накрывается ничем: «нечего одобрять» не смеет снять весь список.
    """
    if not command:
        return False
    body = pattern.removeprefix("Bash(").removesuffix(":*)")
    return command.startswith(body)
