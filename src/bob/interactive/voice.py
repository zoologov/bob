"""voice — голос Боба в живом интерактивном сеансе (BOB-083 .3 / BOB-087.D3).

Тот же канон, что у голоса гейтед-кодера (:mod:`bob.coding.session_voice`): **Боб —
личность**, он дирижирует сеансом от первого лица; **GUPPI — сухой исполнитель**.
Билдеры — ЧИСТЫЕ детерминированные ШАБЛОНЫ (никакого LLM на реплику): вход/выход
режима, честный конец сеанса «сам», вопрос о возобновлении и его исходы.

🔴 Почему отдельный модуль (BOB-087.E, bob-6u2): реплики режима — это словарь ЖИВОГО
ТЕРМИНАЛА, второго bounded context. Пока они лежали в файле голоса гейтед-кодера,
каждая новая реплика интерактива дописывалась в ЧУЖОЙ модуль (и растила чужой узел
графа), а читатель не мог сказать, какие строки чьи. Теперь каждый контекст владеет
своим голосом.

Две строки — :func:`stopped` и :func:`no_session` — ОБЩИЕ: они говорят не про режим, а
про управление сессией как таковой («тормознул», «активной сессии нет»), звучат
одинаково в обоих контекстах и потому ре-экспортируются из голоса coding, а не
дублируются здесь (расхождение формулировок было бы расхождением поведения).
"""

from __future__ import annotations

from bob.coding.session_voice import no_session, stopped

__all__ = [
    "interactive_busy",
    "interactive_ended",
    "interactive_ended_persistent",
    "interactive_failed",
    "interactive_opened",
    "interactive_setup_failed",
    "no_session",
    "resume_cancelled",
    "resume_confirm",
    "resume_failed",
    "resume_nothing",
    "resumed",
    "stopped",
    "stopped_persistent",
    "workspace_opened",
]

# --- Голос Боба (русский — язык проекта; Cyrillic look-alikes интенциональны) ---

# 🔴 Стоп ВОЗОБНОВЛЁННОЙ сессии (BOB-087.D4b): её рабочее место — долгоживущий workspace,
# и он СОЗНАТЕЛЬНО остаётся с накопленной работой. Поэтому реплика та же по интонации, но
# про уборку не говорит ни слова (это была бы ложь) и честно зовёт поднять сессию снова.
_STOPPED_PERSISTENT = (
    "Окей, тормознул. GUPPI свернулся, но всё наработанное осталось на месте — "
    "скажешь поднять, продолжим оттуда же."
)

# Интерактивный терминал (BOB-083 .3): живой двусторонний сеанс в личке — Боб держит
# запущенный claude с открытым stdin, owner направляет его репликами. Реплики короткие,
# явно обозначают ВХОД/ВЫХОД режима (INV-5: честное переключение) и прямой kill.
_INTERACTIVE_OPENED = (
    "Открыл интерактивный терминал — теперь пиши сюда, и я передаю claude вживую. "
    "Чтобы выйти — «стоп»."
)
_INTERACTIVE_BUSY = (
    "Интерактивная сессия уже открыта — сначала заверши её («стоп»), потом откроем новую."
)
_INTERACTIVE_FAILED = "Не смог открыть интерактивный терминал — рабочую копию убрал."
# 🔴 Провал ПОДГОТОВКИ рабочего места (BOB-087.D5b): дерево так и не создалось, убирать
# нечего — поэтому реплика про уборку молчит (иначе врала бы, как врал бы `stopped` о
# сохранённом workspace). Owner всё равно получает ответ: молчание тут — тоже ложь.
_INTERACTIVE_SETUP_FAILED = (
    "Не смог подготовить рабочую копию — интерактив не открыл, ничего не тронул."
)
# 🔴 Сеанс кончился САМ (bob-kv4): claude умер/закрылся без owner-команды. Реплика
# ОБЯЗАНА отличаться от прощания на «стоп» — выдать смерть процесса за исполнение просьбы
# owner'а значило бы приписать ему чужое действие. Пара реплик, как у ``stopped``: судьба
# дерева разная, и голос идёт ЗА ней (эфемерная копия убрана — говорим; накопленный
# workspace остался — не заикаемся об уборке, зовём поднять).
_INTERACTIVE_ENDED = (
    "Слушай, GUPPI сам свернулся — сеанс закрылся без твоей команды. "
    "Рабочую копию убрал; скажешь — открою заново."
)
_INTERACTIVE_ENDED_PERSISTENT = (
    "Слушай, GUPPI сам свернулся — сеанс закрылся без твоей команды. "
    "Всё наработанное осталось на месте — скажешь поднять, продолжим оттуда же."
)

# Возобновление приостановленной работы (BOB-087.D3): owner просит поднять сессию в
# долгоживущем workspace, Боб СНАЧАЛА переспрашивает (предохранитель: поднять живой
# claude в накопленном рабочем месте — сильное действие, оно идёт только с явного «да»),
# и лишь потом докладывает результат. Реплики называют workspace и время той сессии,
# чтобы owner понимал, что именно поднимает — в т.ч. с телефона, без контекста.
_RESUME_CONFIRM = (
    "Нашёл нашу сессию по «{workspace}» — последний раз мы её трогали {when}. "
    "Поднимаю с того же места? Скажи «да» — или «нет», если передумал."
)
# Открытие ДОЛГОЖИВУЩЕГО рабочего места (BOB-087.D5b): в отличие от эфемерного
# интерактива, это дерево переживает «стоп» и копит работу — реплика об этом ЧЕСТНО
# предупреждает, иначе owner ждал бы привычной уборки.
_WORKSPACE_OPENED = (
    "Открыл рабочее место «{workspace}» — оно долгоживущее: всё наработанное там и "
    "останется, скажешь «стоп» — продолжим оттуда же. Пиши сюда, я передаю claude вживую."
)
_RESUME_NOTHING = (
    "По «{workspace}» поднимать нечего — приостановленной сессии я там не нашёл."
)
_RESUME_CANCELLED = "Понял, не трогаю — работа так и лежит, поднимем, когда скажешь."
_RESUMED = (
    "Поднял нашу сессию по «{workspace}» — продолжаем с того же места. "
    "Пиши сюда, я передаю claude вживую; чтобы выйти — «стоп»."
)
# 🔴 На провале возобновления рабочее место НЕ убирается (в нём накоплена работа) —
# реплика об уборке не говорит, иначе она врала бы про судьбу файлов.
_RESUME_FAILED = "Не смог поднять сессию — рабочее место на месте, попробуем ещё раз?"


def stopped_persistent() -> str:
    """Реплика «остановил, работа осталась»: сеанс погашен, workspace НЕ убран.

    Парная к :func:`~bob.coding.session_voice.stopped` для ВОЗОБНОВЛЯЕМОЙ сессии
    (BOB-087.D4b): её дерево — долгоживущий workspace с накопленной работой, он
    переживает остановку. Реплика об уборке не говорит (иначе врала бы owner'у) и зовёт
    поднять сессию снова.
    """
    return _STOPPED_PERSISTENT


def interactive_opened() -> str:
    """Реплика «интерактив открыт» (BOB-083 .3): вход в живой двусторонний режим."""
    return _INTERACTIVE_OPENED


def interactive_busy() -> str:
    """Отказ: интерактивная сессия уже открыта — одна за раз (сначала «стоп»)."""
    return _INTERACTIVE_BUSY


def interactive_failed() -> str:
    """Реплика «не открыл»: спавн живого claude сорвался, рабочая копия убрана."""
    return _INTERACTIVE_FAILED


def interactive_setup_failed() -> str:
    """Реплика «не подготовил рабочее место»: worktree не создался, спавна не было.

    Парная к :func:`interactive_failed` для провала, случившегося РАНЬШЕ спавна
    (BOB-087.D5b): там копия действительно создавалась и убрана, здесь создавать её не
    вышло — и реплика про уборку не говорит ни слова, чтобы не врать про судьбу файлов.
    """
    return _INTERACTIVE_SETUP_FAILED


def interactive_ended() -> str:
    """Реплика «сеанс кончился сам»: claude завершился БЕЗ owner-команды (bob-kv4).

    Парная к :func:`~bob.coding.session_voice.stopped`, но принципиально другая по
    смыслу: там сеанс погасил owner, здесь процесс кончился сам (краш/выход/обрыв
    потока). Выдать одно за другое — значит приписать owner'у действие, которого он не
    совершал, поэтому реплика отдельная. Эфемерная рабочая копия при этом действительно
    убрана — об этом сказано честно.
    """
    return _INTERACTIVE_ENDED


def interactive_ended_persistent() -> str:
    """Реплика «сеанс кончился сам, работа осталась»: то же, но в ДОЛГОЖИВУЩЕМ workspace.

    Пара к :func:`interactive_ended` по той же логике, что :func:`stopped_persistent` — к
    :func:`~bob.coding.session_voice.stopped`: накопленное дерево переживает конец сеанса,
    поэтому про уборку не говорится ни слова (это была бы ложь), а owner слышит
    приглашение поднять сессию.
    """
    return _INTERACTIVE_ENDED_PERSISTENT


def resume_confirm(*, workspace: str, when: str) -> str:
    """Вопрос-подтверждение: «нашёл сессию по <workspace> от <when> — поднимаю?».

    🔴 Это ВОПРОС, а не доклад: Боб ничего не поднимает, пока owner не ответит «да».
    ``when`` — уже отформатированная человеческая метка времени той сессии.
    """
    return _RESUME_CONFIRM.format(workspace=workspace, when=when)


def workspace_opened(workspace: str) -> str:
    """Реплика «открыл рабочее место»: сеанс идёт в ДОЛГОЖИВУЩЕМ workspace (BOB-087.D5b).

    Парная к :func:`interactive_opened`, но честно предупреждает о РАЗНИЦЕ, которая
    касается owner'а: это дерево на «стоп» не убирается, оно копит работу между сеансами
    (и потому его потом можно поднять). Молчание об этом было бы тем же классом
    неправды, что и доклад об уборке сохранённого дерева.
    """
    return _WORKSPACE_OPENED.format(workspace=workspace)


def resume_nothing(workspace: str) -> str:
    """Честный отказ: по этому workspace приостановленной сессии не нашлось."""
    return _RESUME_NOTHING.format(workspace=workspace)


def resume_cancelled() -> str:
    """Реплика на «нет»: возобновление отменено, работа осталась нетронутой."""
    return _RESUME_CANCELLED


def resumed(workspace: str) -> str:
    """Реплика «поднял»: сессия workspace продолжена с того же места."""
    return _RESUMED.format(workspace=workspace)


def resume_failed() -> str:
    """Реплика «не поднял»: спавн сорвался; рабочее место НЕ убрано (в нём работа)."""
    return _RESUME_FAILED
