"""denial_voice — голос Боба, когда он упёрся в запрет и просит слова у владельца.

ОДНА ответственность: собрать то, что владелец ПРОЧТЁТ в личке про отказ, — вопрос и два
коротких ответа на «да» / «нет». Ни транспорта, ни решений, ни знания о ``claude``.

🔴 Голос БОБА, а не GUPPI (канон BOB-090.D, :mod:`bob.coding.speaker`): просьба
разрешения — социальный акт (:data:`~bob.coding.speaker.MessageKind.PERMISSION_REQUEST`),
а механика прогона остаётся за GUPPI. Ту же линию раздела держит и композиция: firehose
идёт ботом GUPPI, а этот вопрос — нотификатором самого Боба.

🔴 БЕЗ КНОПОК И БЕЗ СЛЕШЕЙ — решение владельца от 2026-08-15, и оно категорично: «всё
общение с Бобом должно быть живым и человечным», «давай все словами и живой речью».
Поэтому здесь нет ни ``/approve``, ни «нажми», ни списка вариантов: Боб задаёт вопрос, а
ответ ловит машина висящего вопроса
(:class:`~bob.interactive.permission_negotiation.PermissionNegotiation`) обычными «да» и
«нет» — теми же предикатами, которыми уже разбирается «поднимаю?».

Лечение скриптовости — то же разделение ролей, что в :mod:`bob.proactivity.rule_voice`
(владелец про прежнюю сборку: «выглядит очень скриптовано, а не человечно»), а не перевод
строки и не генерация:

* **служебный текст CLI не произносится вовсе** — сюда он и НЕ ПЕРЕДАЁТСЯ: билдер
  принимает :class:`~bob.interactive.permission_denial.PermissionDenial`, а в нём поля
  ``message`` нет. Значит английское «This command requires approval» не может стать
  телом русской фразы ни при какой доработке вызывающего;
* **чего именно он хотел — цитата его собственного действия**: команда как есть, потому
  что это единственная честная формулировка (тот же приём, что с цитатой просителя в
  :mod:`bob.social.permission.request_voice`);
* **почему он спрашивает — говорит сам Боб**, и по-разному: толкнуть ветку наружу, снести
  файлы и слить PR — это РАЗНЫЕ тревоги, и звучат они разными словами, а не одним
  шаблоном с подстановкой;
* **пустых слотов нет по конструкции**: без команды фраза склеивается из непустых частей,
  поэтому ни ``«..»``, ни висящего двоеточия не рождается.

🔴 И ЧЕСТНО ПРО ГРАНИЦУ, которую этот голос НЕ переходит: «доразрешить на месте» нельзя —
конкретный ``tool_use`` отказан необратимо, это ограничение CLI. «Да» владельца исполняется
ПОВТОРНЫМ заходом (``--resume``), а если возвращаться уже некуда, Боб так и говорит
(:func:`permission_unreachable`), а не молчит и не делает вид, что сделал.

Чисто и детерминированно: никакого LLM на реплику, никакого I/O, одинаковый вход →
одинаковый результат.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from bob.interactive.permission_denial import PermissionDenial

__all__ = [
    "permission_declined",
    "permission_lifted",
    "permission_question",
    "permission_stuck",
    "permission_unreachable",
]


@dataclass(frozen=True, slots=True)
class _Wording:
    """Три части реплики: что Боб собрался делать, почему не сам и сам вопрос."""

    notice: str
    why: str
    question: str


# Сеть наружу: ветка уезжает туда, откуда её уже не отозвать молча.
_PUSH = _Wording(
    notice="Дошёл до места, где ветку надо толкнуть наружу",
    why="Наружу я без твоего слова не хожу",
    question="Отправлять?",
)
# Мёрж: И-1 — main остаётся за владельцем, и Боб про это помнит вслух.
_MERGE = _Wording(
    notice="Работа доехала до мёржа",
    why="Сливать — твой ход, не мой",
    question="Сливаем?",
)
# Удаление: единственное необратимое, которое встроенный гейт CLI пропускает молча.
_DELETE = _Wording(
    notice="Хочу снести вот это",
    why="Удаление обратно не отыграешь, поэтому спрашиваю",
    question="Сносить?",
)
# Откат: пропадёт именно НЕЗАКОММИЧЕННОЕ, и об этом стоит сказать прямо.
_RESET = _Wording(
    notice="Хочу откатить рабочее дерево",
    why="Незакоммиченное при этом пропадёт",
    question="Откатывать?",
)
# Remotes: меняется, КУДА уедет следующий push, — тише и опаснее самого push'а.
_REMOTE = _Wording(
    notice="Понадобилось переписать, куда смотрит этот репозиторий",
    why="Такое молча не делаю",
    question="Разрешишь?",
)
# Прочая сеть: и утечка наружу, и чужой код внутрь.
_NETWORK = _Wording(
    notice="Мне тут надо сходить в сеть",
    why="В сеть без спроса не лезу",
    question="Можно?",
)
# Всё остальное, включая отказы ВСТРОЕННОГО гейта CLI: Боб не домысливает, чем именно
# команда опасна, — он честно говорит, что упёрся, и показывает её.
_OTHER = _Wording(
    notice="Упёрся в запрет",
    why="Сам такое не решаю",
    question="Разрешишь?",
)

_DASH = " — "


def permission_question(denial: PermissionDenial) -> str:
    """Собрать вопрос владельцу: чего Боб хотел, почему спрашивает и сам вопрос.

    ``denial`` — ВНУТРЕННИЙ разбор события: из него в текст попадает только то, что Боб и
    сам бы сказал (команда или имя инструмента), а служебной строки CLI в нём нет вовсе.
    """
    wording = _wording_for(denial)
    return f"{wording.notice}{_shown(denial)}. {wording.why}. {wording.question}"


def permission_stuck(denial: PermissionDenial) -> str:
    """Сказать про отказ, который Боб снять НЕ МОЖЕТ, — и не задавать пустого вопроса.

    Так выглядит отказ инструменту целиком (например ``WebFetch``) или отказ, чей вызов
    до нас не дошёл: команды нет, значит нечего разрешать точечно, и «разрешаешь?» было
    бы вопросом, на который «да» ничего не изменит. 🔴 Молчать при этом нельзя — молчащий
    конвейер, вставший на невидимом запрете, и есть дефект, который лечит этот срез.
    """
    tool = denial.tool_name.strip()
    named = f" на инструмент `{tool}`" if tool else ""
    return (
        f"Упёрся в запрет{named} и снять его сам не могу — это уже настройка на твоей "
        "стороне. Пока обхожусь без него."
    )


def permission_lifted(command: str) -> str:
    """Ответ на «да»: Боб возвращается в работу и называет, что именно делает.

    Команда произносится ещё раз нарочно: между вопросом и ответом мог пройти час, и
    владелец должен видеть, ЧТО именно он сейчас разрешил, а не помнить это.
    """
    shown = command.strip()
    if not shown:
        return "Понял, возвращаюсь к тому месту."
    return f"Понял, делаю: `{shown}`"


def permission_declined() -> str:
    """Ответ на «нет»: коротко и без упрёка — Боб идёт дальше без этого шага."""
    return "Понял, не трогаю. Пойду дальше без этого."


def permission_unreachable() -> str:
    """Честный ответ, когда возвращаться уже некуда: сеанса нет, повторять нечего.

    🔴 Именно та граница, которую нельзя замолчать: отказ по конкретному ``tool_use``
    необратим, «доразрешить» на месте CLI не позволяет, а повторный заход возможен, пока
    жива нить сессии. Нет нити — Боб говорит об этом, а не изображает исполнение.
    """
    return (
        "Твоё «да» принял, но возвращаться уже некуда — та сессия кончилась. "
        "Скажи, если поднять заново."
    )


def _wording_for(denial: PermissionDenial) -> _Wording:
    """Выбрать слова Боба по тому, что именно он собирался сделать.

    Признаки сравниваются В ТЕЛЕ функции отдельными проверками, а не таблицей-константой
    наверху файла: подмена любой ветки тогда — видимый мутант, и гейт измеряет саму
    политику, а не форму записи (``MUTATION.md``, §«Порог и честность»).

    🔴 Здесь ПОДСТРОКА, а не префикс — и это осознанно другое правило, чем у запрета
    (:mod:`bob.interactive.tool_permissions`, где префикс диктует сам CLI): выбор слов —
    это про смысл действия, и ``cd . && git push …`` для Боба такой же push.
    """
    command = denial.command.strip()
    if not command:
        return _OTHER  # тотальность: без команды сюда не ходят (см. permission_stuck)
    if command.startswith("rm "):
        # 🔴 Удаление узнаётся НАЧАЛОМ, а не подстрокой: «confirm …» содержит «rm ».
        return _DELETE
    by_marker = (
        ("git push", _PUSH),
        ("gh pr merge", _MERGE),
        ("git reset", _RESET),
        ("git remote", _REMOTE),
        ("curl", _NETWORK),
        ("wget", _NETWORK),
    )
    for marker, wording in by_marker:
        if marker in command:
            return wording
    return _OTHER


def _shown(denial: PermissionDenial) -> str:
    """Показать предмет отказа: команду, иначе имя инструмента, иначе НИЧЕГО.

    «Ничего» — это отсутствие куска фразы целиком, а не пустая подстановка: так двойная
    точка и висящее тире не рождаются даже на вырожденном входе.
    """
    subject = denial.command.strip() or denial.tool_name.strip()
    return f"{_DASH}`{subject}`" if subject else ""
