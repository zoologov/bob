"""Первый кадр живой сессии — чем Боб ставит задачу конвейеру (BOB-088, срез 2).

ОДНА ответственность: собрать ТЕКСТ, которым начинается живая сессия ``claude``, — задачу
owner'а плюс указание вести её по процессу репозитория. Ни одного побочного эффекта: кто и
когда отправит этот текст в открытый stdin, решает
:class:`~bob.interactive.usecases.session.InteractiveSessionManager`.

🔴 ЗАЧЕМ ЭТО ДОМЕН, А НЕ СТРОКА В АДАПТЕРЕ (§0.3 п.7). До этого среза ``runner.open(...)``
вызывался и в сессию НЕ уходило ничего: ``claude`` стартовал с пустым контекстом и ждал,
пока owner напишет сам, а аргумент задачи работал только меткой сессии и именем ветки.
Значит текст этого кадра и есть то, что превращает «claude что-то делает» в конвейер, —
поведение, а не оформление. Объявить его mutation-целью и оставить в адаптере значило бы
прогонять НОЛЬ мутантов и отчитаться «покрыто»: ``*/adapters/*`` исключены конвенцией.
Пакет ``src/bob/coding`` в ``[tool.mutmut].source_paths`` уже есть, поэтому модуль здесь
попадает под гейт по построению.

🔴 ПОЧЕМУ ЗНАЧЕНИЯ — В ТЕЛЕ ФУНКЦИИ, А НЕ МОДУЛЬНЫМИ КОНСТАНТАМИ (MUTATION.md, «Порог и
честность»): mutmut мутирует только тела функций, и вынесенный наверх текст промпта лежал
бы в песочнице БАЙТ-В-БАЙТ — гейт был бы фиктивным ровно на том, ради чего заведён.

🔴 ЧЕГО ЭТОТ КАДР НЕ РЕШАЕТ. Он не классифицирует работу «эпик или не эпик»: такая
эвристика была бы скриптованностью на входе в самый мощный шов (урок BOB-076 — дешёвая
мис-классификация однажды уже запустила runaway-кодер). Кадр НАЗЫВАЕТ ПРАВИЛО, а решает
модель, читая ``CLAUDE.md`` — ту же карту, по которой работает человек.
"""

from __future__ import annotations

__all__ = ["pipeline_first_frame"]


def pipeline_first_frame(task: str) -> str | None:
    """Собрать первый кадр сессии по задаче ``task``; ``None`` — кадра нет вовсе.

    Пустая (или из одних пробелов) задача даёт ``None``, и это решение, а не мелочь:
    «Задача от owner'а:» без задачи модель ДОДУМАЕТ и начнёт вести конвейером выдуманную
    работу. Кадра нет — сессия просто открыта и ждёт owner'а, ровно как до среза.

    Задача едет ДОСЛОВНО (срезаны только внешние пробелы), включая переводы строк: owner
    вправе вставить в постановку несколько абзацев, а в stdin кадр всё равно уедет ОДНОЙ
    строкой — экранированием занимается
    :func:`bob.interactive.adapters.runner.encode_user_message`.
    """
    task = task.strip()
    if not task:
        return None
    return "\n".join(
        (
            f"Задача от owner'а: {task}",
            "",
            "Веди её по CLAUDE.md в корне этого рабочего дерева: это входная точка "
            "процесса, прочти её первой.",
            "Эпик или иначе многобеадная работа — через /coordinator, роли (dev / test / "
            "review / tech-writer) запускай СУБАГЕНТАМИ.",
            "Одна маленькая беада — возьми роль inline по .claude/agents/<роль>.md.",
            "Трекер bd доступен из этого рабочего места: беаду возьми или заведи и веди "
            "её состояние там, а не в голове.",
            "Это постановка, а не разминка: начинай сам, отдельной команды не будет.",
        )
    )
