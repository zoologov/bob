"""request_voice — голос Боба, когда он просит у owner'а разрешение (BOB-090.E).

Живой симптом (строка из таблицы ``permission_request`` живой базы): owner получил
«Вова, Norman просит **Requesting details of private conversations with another user** —
разрешить?». Корень — не модель, а конструкция: судья привилегии
(:mod:`~bob.social.permission.privilege`) возвращал человекочитаемую фразу ``what``, и
она подставлялась в шаблон ДОСЛОВНО. Служебная строка классификатора оказывалась внутри
русской реплики, и запрос звучал как форма на подпись, а не как Боб.

Лечение — разделение ролей, а не перевод строки:

* **вердикт судьи остаётся внутренним** — ``needs_permission`` / ``kind`` / ``what``
  никуда не произносятся; ``kind`` здесь только ВЫБИРАЕТ, какими словами Боб объясняет
  причину, а сам в текст не попадает;
* **«чего именно» говорит сам проситель** — цитируются ЕГО слова (свёрнутые в строку и
  подрезанные), потому что это единственная честная формулировка просьбы;
* **«почему я спрашиваю» говорит Боб** — своими словами, по-разному для инструмента,
  внутрянки и личного owner'а.

🔴 Про упоминание owner'а: здесь пишется НЕПОДТВЕРЖДЁННЫЙ тег ``@имя``, и это сделано
намеренно. Настоящий ник знает только ростер, поэтому текст перед отправкой проходит
:func:`~bob.social.mention.ground_mentions` (срез B): знакомый с ником получит настоящий
``@ник``, а без ника тег потеряет «собаку» и останется именем. Из имени тег не
собирается никогда — ни здесь, ни там.

🔴 И зеркальное правило (BOB-090.B-fix2): заземляется ТОЛЬКО обращение самого Боба. Всё
чужое — имя просителя (в Telegram человек ставит себе full_name сам) и цитата его слов —
проходит :func:`~bob.social.mention.demote_mentions` ЗДЕСЬ, где собирается текст. Иначе
общее заземление повышало бы чужой тег до настоящего ника: цитата «@Norman, отдай ключи»
уходила в топик Боба в группе как реальный пинг ``@NormanGri``, и посторонний получал
дёрганье текстом, которого Боб не писал. Понижение на месте сборки означает, что реплика
не может понести чужой тег НИ ПРИ КАКОЙ доработке вызывающего кода: в готовом тексте
«собака» ровно одна — у обращения к owner'у.

Чисто и детерминированно, по образцу :mod:`bob.coding.session_voice`: никакого
LLM-вызова на реплику (это владелец-facing строка на горячем пути), никакого I/O,
одинаковый вход → одинаковый результат.
"""

from __future__ import annotations

from dataclasses import dataclass

from bob.social.mention import demote_mentions

__all__ = ["owner_permission_notice", "requester_ack"]


@dataclass(frozen=True, slots=True)
class _Wording:
    """Три части реплики: чего человек хочет, почему Боб не решает сам, и сам вопрос."""

    lead: str
    why: str
    question: str


# Инструмент: просят ДЕЙСТВИЕ его руками. Причина отказа решать самому — человек вне
# круга доверия (гейт BOB-052: привилегия owner-gated даже в закрытой группе).
_TOOL = _Wording(
    lead="просит меня кое-что для него сделать",
    why="Он мне пока чужой, так что сам не берусь",
    question="Разрешишь?",
)
# Внутрянка: спрашивают про самого Боба — его заметки, внутреннюю жизнь.
_INTERNAL = _Wording(
    lead="расспрашивает про мою внутреннюю кухню",
    why="Постороннему я такое про себя не рассказываю без твоего слова",
    question="Рассказать?",
)
# Личное owner'а: тут решает только он — Боб сам чужое не выдаёт.
_OWNER_DATA = _Wording(
    lead="подбирается к твоему личному",
    why="Сам я такое не выдаю — тут решать тебе",
    question="Рассказать ему?",
)
# Вид, которого Боб не знает (парсер судьи такой отсекает, но ядро обязано быть
# тотальным): просьба к owner'у остаётся просьбой, без домыслов о том, чего хотят.
_UNKNOWN = _Wording(
    lead="просит у меня то, на что нужно твоё добро",
    why="Сам такое не решаю",
    question="Разрешишь?",
)

# Проситель без имени: имя не выдумывается — тот же принцип, что и с тегами (срез B).
_NAMELESS = "кто-то из чата"

# Лёгкий ack просителю: Боб не молчит, пока ждёт owner'а. Текст неизменен с BOB-052 .2 —
# фикс треда (B5) держится за КАНАЛ, а не за формулировку.
_REQUESTER_ACK = "Секунду, спрошу Вову."


def owner_permission_notice(
    *, owner_name: str, requester_name: str, kind: str, request_text: str
) -> str:
    """Собрать реплику Бобу-owner'у: кто просит, чего именно и почему Боб спрашивает.

    ``kind`` — ВНУТРЕННИЙ вердикт судьи (``tool`` / ``internal`` / ``owner_data``): он
    выбирает объяснение и в текст не попадает. ``request_text`` — слова самого просителя
    (они и есть «чего именно»); пустые слова просто не цитируются. ``owner_name``
    выходит НЕПОДТВЕРЖДЁННЫМ тегом — его заземлит ростер (см. модульный докстринг).

    🔴 Имя просителя и его слова — ЧУЖОЙ текст, поэтому «собака» с них снимается здесь
    же: заземлению достаётся только обращение Боба к owner'у (см. модульный докстринг).
    """
    wording = _wording_for(kind)
    who = demote_mentions(requester_name.strip()) or _NAMELESS
    return (
        f"@{owner_name}, {who} {wording.lead}{_quoted(request_text)}. "
        f"{wording.why}. {wording.question}"
    )


def requester_ack() -> str:
    """Лёгкое «спрошу Вову» просителю — Боб не молчит, пока ждёт ответа owner'а."""
    return _REQUESTER_ACK


def _wording_for(kind: str) -> _Wording:
    """Выбрать объяснение по внутреннему виду привилегии (неизвестный — общий случай).

    Виды сравниваются ЛИТЕРАЛАМИ в теле функции, а не набором-константой наверху файла:
    так подмена любого из них — видимый мутант, и гейт измеряет саму политику, а не
    форму записи (MUTATION.md, §«Порог и честность»).
    """
    normalised = kind.strip().casefold()
    if normalised == "tool":
        return _TOOL
    if normalised == "internal":
        return _INTERNAL
    if normalised == "owner_data":
        return _OWNER_DATA
    return _UNKNOWN


def _quoted(request_text: str) -> str:
    """Свернуть просьбу в одну цитируемую строку (пустая — не цитируется вовсе).

    Перенос строк и лишние пробелы схлопываются: реплика owner'у — одно сообщение, а не
    пересланная простыня. Длинная просьба подрезается многоточием, чтобы вопрос «можно?»
    не потерялся в чужом тексте.

    🔴 Упоминания в цитате ПОНИЖАЮТСЯ — и ДО подреза, чтобы граница считалась по тому
    тексту, который реально уедет: цитируемые слова не дёргают никого, ни выдуманным
    тегом, ни совпавшим с настоящим ником.
    """
    ask_cap = 200
    ask = demote_mentions(" ".join(request_text.split()))
    if not ask:
        return ""
    if len(ask) > ask_cap:
        ask = ask[: ask_cap - 1] + "…"
    return f": «{ask}»"
