"""Как Боб зовёт git в каталоге, за содержимое которого отвечает МОДЕЛЬ (bob-a6b.14).

ОДНА ответственность: не дать репозиторию, которым распоряжается модель, исполнить свой код
в процессе САМОГО Боба и увезти его push мимо форка. Решения, ни одного побочного эффекта:

* :func:`hardened_git_argv` — префикс любого нашего вызова git в таком каталоге;
* :func:`unsafe_local_config` — какие ключи локального конфига означают «дальше не идём»
  (:data:`LOCAL_CONFIG_QUERY` — форма, которой этот конфиг спрашивают).

🔴 ЗАЧЕМ ОТДЕЛЬНОЕ ЯДРО (ревью bob-a6b.6, MAJOR-7 — и это ФАКТ, воспроизведённый ревьюером
на настоящем git, а не рассуждение). Три прохода эпик закрывал окружение СПАВНА. Но
``commit_and_push`` идёт в процессе самого Боба — намеренно вне изоляции: у него
credential-хелпер владельца и его ssh-ключ с правом записи в апстрим. А работает он внутри
каталога, которым модель распоряжается целиком, включая ``<клон>/.git``. Итог: подложенные
ею ``.git/hooks/{pre-commit,post-commit,pre-push}`` ИСПОЛНИЛИСЬ в процессе Боба, а
прописанный локально ``remote.origin.pushurl`` увёл ветку В АПСТРИМ вместо форка. Ствол при
этом не доставался (refspec фиксирован), и новой способности модели это не давало (прямой
``ssh`` уже назван открытым) — но это пересечение границы, которое МОЛЧА ОБЕСЦЕНИЛО БЫ
BOB-093: под раздельным UID хук из клона всё равно исполнился бы на нашей стороне.

🔴 СОСТАВ ВЫБРАН ПОПЫТКАМИ на настоящем git 2.49, а не по документации (пары
контроль/защита — ``tests/infrastructure/coding/test_untrusted_repo_real_git.py``). Что
воспроизведено как ЖИВОЕ и чем закрыто:

* ХУКИ (``pre-commit`` / ``post-commit`` / ``pre-push``) — единственный вектор, которому
  НЕ НУЖЕН конфиг: модель просто пишет файлы. Закрыт ``core.hooksPath=/dev/null``; пара в
  argv перебивает и ``core.hooksPath``, прописанный моделью локально (проверено отдельно).
  ``--no-verify`` на ``commit``/``push`` — второй слой, и он НЕ равен первому: проверено,
  что с одним ``--no-verify`` ``post-commit`` всё равно исполняется;
* ``core.fsmonitor`` — значение исполняется как команда на ``add``/``status``. Закрыт
  парой ``core.fsmonitor=false``;
* ``commit.gpgsign=true`` + ``gpg.program=<скрипт>`` — исполнение произвольной команды
  ровно на нашем ``commit``. Закрыт парой ``commit.gpgSign=false``: гасится не имя
  программы, а сама подпись, поэтому имя перестаёт значить что-либо;
* ``remote.origin.pushurl`` — увёл ветку в апстрим. Закрыт push'ем ПО ЗНАЧЕНИЮ ``fork_url``
  (значение по построению без кредов — :func:`bob.coding.clone_plan.is_credential_free_url`);
* ``filter.<d>.clean`` (+ ``.gitattributes`` в дереве) — исполнился на ``add -A`` ДАЖЕ с
  полным набором пар: у фильтров нет ключа-выключателя. Не закрывается argv вовсе;
* ``url.<апстрим>.pushInsteadOf`` — увёз ветку в апстрим ДАЖЕ при push'е по значению:
  перезапись адреса происходит после разбора argv, а погасить её можно только для НАЗВАННОЙ
  подсекции (тот же многозначный ключ, на котором эпик спотыкался в bob-5ao). Тоже не
  закрывается argv.

Последние два и есть причина третьего слоя — ОТКАЗА. Он ALLOW-список, а не перечень опасных
ключей, и вот почему (обе дороги воспроизведены): ``include.path`` подключает файл, ключи
которого ``config --local --list`` НЕ ПОКАЗЫВАЕТ — фильтр из такого файла исполнился, а
``config --local --get`` отвечал «нет такого ключа»; ``extensions.worktreeConfig=true``
уводит ключи в ``.git/config.worktree``, невидимый для ``--local``. Перечень опасных ключей
не увидел бы ни одной из этих дорог; ALLOW-список видит сам незнакомый ключ.

🔴 И ЧЕТВЁРТЫЙ ВЕКТОР — СОСТАВ САМОГО СПИСКА (ревью bob-a6b.6, MAJOR-8; оба факта
воспроизведены через настоящий ``GitClone.commit_and_push``, отказа не было). Список судит
ИМЕНА, а два разрешённых имени опасны ЗНАЧЕНИЕМ:

* ``core.worktree`` — модель указала им рабочее дерево ВЛАДЕЛЬЦА, и ``add -A`` собрал его:
  в ветку форка уехал незакоммиченный черновик владельца (``secret_notes.md``), а работа
  Боба (``bob_work.py``) в ветку не попала. Дорога утечки чужой работы. Ключ УБРАН из
  списка: чистый ``git clone`` его не пишет вовсе (снято с настоящего git, см. состав
  :data:`_ALLOWED_KEYS`), поэтому в конфиге клона он бывает только от модели;
* ``user.name`` / ``user.email`` — модель прописала их локально, и коммит в форке оказался
  подписан ВЛАДЕЛЬЦЕМ (``Vladimir Zoologov <…@gmail.com>``): прямое попадание в US-2, ради
  которого делался срез D. Из списка их не выкинуть — их пишет наша же последовательность
  заведения, — поэтому решает теперь не конфиг, а ПАРА В ARGV (``identity`` в
  :func:`hardened_git_argv`), ровно по тому же доводу, по которому там уже стоят
  ``hooksPath``/``fsmonitor``/``gpgSign``.

Третье имя того же рода — ``remote.origin.url`` — оставлено сознательно и названо как
ИЗВЕСТНАЯ ГРАНИЦА: его пишет сам ``git clone``, а сегодня он инертен, потому что push идёт
по ЗНАЧЕНИЮ ``fork_url``, а единственный ``fetch`` случается при заведении клона, до того
как модель к нему прикоснулась. Появится ``fetch``/``pull`` на существующем клоне — адрес
придётся сверять со значением из конфигурации Боба.

🔴 ЧЕСТНАЯ РАМКА (иначе доки опять обещают больше, чем схема держит — Issues #49):

* Пары в argv от МОМЕНТА проверки не зависят: они едут в каждой команде. Отказ по конфигу
  — зависит: между опросом конфига и ``add`` живой сеанс ``claude`` вправе дописать ключ.
  Это мера против НЕЧАЯННОГО и против уже подложенного, а не против гонки;
* проверяется конфиг КЛОНА, где мы сами его и завели, поэтому незнакомый ключ — сигнал. В
  режиме linked worktree локальный конфиг — конфиг ВЛАДЕЛЬЦА (в нём законно живёт,
  например, ``merge.beads.driver``), отличить его правку от правки модели нечем, и там
  работают только пары в argv. Это ещё один довод за клон, а не за worktree;
* ``core.pager`` / ``core.editor`` / ``diff.<d>.textconv`` исполнить в нашем процессе НЕ
  УДАЛОСЬ: раннер всегда отдаёт git PIPE (не tty), а ``commit`` идёт с ``-m``. Пары на них
  не заведены сознательно — заявлять непроверенное не наш жанр; в клоне их закрывает
  отказ по незнакомому ключу;
* и то, что осталось: рабочее дерево клона модель меняет как хочет — но ``.git/hooks`` и
  локальный конфиг она меняет ДЛЯ ЧУЖОГО ПРОЦЕССА, то есть это не «тот же UID», а доверие
  вызывающего. Полностью класс закрывает раздельный UID — беада BOB-093.
"""

from __future__ import annotations

__all__ = ["LOCAL_CONFIG_QUERY", "hardened_git_argv", "unsafe_local_config"]

#: Пары ``-c key=value``, которыми наш вызов гасит исполнение кода, названного каталогом.
#: Каждая — воспроизведённый факт из докстроки модуля, ни одной «по аналогии».
_HARDENING_PAIRS: tuple[tuple[str, str], ...] = (
    # Каталог хуков уводится в /dev/null: файлов внутри быть не может, значит ни один хук
    # не найдётся — ни из ``.git/hooks``, ни из каталога, названного локальным конфигом.
    ("core.hooksPath", "/dev/null"),
    # Монитор файловой системы — команда из конфига, которую git запускает на add/status.
    ("core.fsmonitor", "false"),
    # Подпись коммита — единственная причина, по которой git запустил бы ``gpg.program``.
    ("commit.gpgSign", "false"),
)

#: Форма опроса конфига РЕПОЗИТОРИЯ. ``--local``, а не полный ``--list``: полный показал бы
#: и конфиг владельца, то есть проверка начала бы судить его настройки. ``-z`` — потому что
#: значение вправе содержать перевод строки, и построчный разбор увидел бы выдуманные ключи.
LOCAL_CONFIG_QUERY: tuple[str, str, str, str] = ("config", "--local", "--list", "-z")

#: Ключи, которые в конфиге клона оставляют САМ ``git clone`` и наша последовательность
#: заведения места. 🔴 Состав СНЯТ С НАСТОЯЩЕГО git 2.49 на этой машине (и перепроверён
#: заново в MAJOR-8: ``git clone file://…`` + наши шаги дали ровно
#: ``core.repositoryformatversion``, ``core.filemode``, ``core.bare``,
#: ``core.logallrefupdates``, ``core.ignorecase``, ``core.precomposeunicode``,
#: ``remote.origin.url``, ``remote.origin.fetch``, ``branch.main.remote``,
#: ``branch.main.merge`` + наши ``user.name``/``user.email``), а не выписан из документации.
#: У каждого имени здесь ОДНО оправдание: даже прописанное моделью, его значение не может
#: назвать ни команду, ни второй адрес push'а — это переключатель (``true``/``false``),
#: число, формат или адрес, которому мы всё равно не верим (см. границу
#: ``remote.origin.url`` в докстроке модуля).
_ALLOWED_KEYS: frozenset[str] = frozenset(
    {
        # Формат репозитория и свойства файловой системы: значение — число или булево.
        "core.repositoryformatversion",
        "core.filemode",
        "core.bare",
        "core.logallrefupdates",
        "core.ignorecase",  # обе — macOS-специфика, пишет сам clone
        "core.precomposeunicode",
        # 🔴 Эти два на ЭТОЙ машине git не написал (файловая система их не требует), но
        # пишет там, где свойство иное (Windows / FS без симлинков). Оставлены не «на
        # всякий случай», а по тому же критерию: значение булево, назвать им нельзя ничего.
        "core.symlinks",
        "core.hidedotfiles",
        # 🔴 ``core.worktree`` тут БОЛЬШЕ НЕТ (MAJOR-8): чистый clone его не пишет вовсе, а
        # модель, указав им дерево ВЛАДЕЛЬЦА, увезла в форк его незакоммиченный черновик.
        # Формат объектов (sha1/sha256) — единственное расширение, которое пишет сам git и
        # которое не несёт ни кода, ни адреса. ``extensions.worktreeConfig`` сюда НЕ входит
        # намеренно: он прячет ключи от ``--local`` (проверено).
        "extensions.objectformat",
        # Адрес единственного remote'а и его refspec. Адресу мы не верим: push идёт по
        # ЗНАЧЕНИЮ ``fork_url`` (названная граница — в докстроке модуля).
        "remote.origin.url",
        "remote.origin.fetch",
        # Подпись работы Боба: её пишет наша последовательность заведения, а РЕШАЕТ её
        # теперь пара в argv — значение из конфига клона больше ничего не определяет.
        "user.name",
        "user.email",
    }
)

#: Ключи ветки, которые пишет сам git при ``switch``/``push -u``: куда ветка смотрит. Всё
#: остальное в этой секции (``pushremote``, ``rebase``) меняет, КУДА уедет работа.
#: ``vscode-merge-base`` пишет редактор владельца, когда он открывает клон Боба глазами;
#: значение — имя ref'а, кода не несёт, и падать на этом было бы глупо.
_ALLOWED_BRANCH_KEYS: frozenset[str] = frozenset({"remote", "merge", "vscode-merge-base"})

_BRANCH_SECTION = "branch."


def hardened_git_argv(
    git_bin: str,
    *,
    path: str | None = None,
    identity: tuple[tuple[str, str], ...] = (),
) -> list[str]:
    """Собрать префикс git-вызова, которым каталог не исполнит свой код в нашем процессе.

    ``path`` — репозиторий, к которому обращаемся (``-C <path>``); ``None`` для ``git
    clone``, где каталога ещё нет, а пары уже нужны (клон исполняет ``post-checkout`` из
    шаблона). Пары стоят ДО подкоманды — иначе git читает их как её аргументы — и каждая
    едет отдельными элементами argv, без склейки в шелл.

    ``identity`` — ключ/значение ПОДПИСИ (``user.name``/``user.email``,
    :func:`bob.coding.clone_plan.identity_pins`), приколоченные тем же способом. 🔴 Они
    здесь по той же причине, что и остальные пары, и это ФАКТ MAJOR-8: прописав
    ``user.name`` локально, модель добилась того, что коммит в форке подписан ВЛАДЕЛЬЦЕМ.
    Пустой набор — ОСОЗНАННЫЙ выбор режима linked worktree: там репозиторий принадлежит
    владельцу, его подпись в нём законна, и прикалывать поверх ``bob[ai]`` значило бы
    менять OFF-путь ещё и в этом (см. ``tests/infrastructure/coding/
    test_off_path_real_git.py``).

    🔴 Пары в argv сильнее локального конфига репозитория и не зависят от момента
    проверки: они едут в КАЖДОЙ команде. Состав и его границы — в докстроке модуля.
    """
    argv = [git_bin]
    for key, value in (*_HARDENING_PAIRS, *identity):
        argv += ["-c", f"{key}={value}"]
    if path is not None:
        argv += ["-C", path]
    return argv


def unsafe_local_config(listing: str) -> tuple[str, ...]:
    """Назвать ключи конфига клона, которых наша последовательность там не оставляла.

    ``listing`` — вывод ``git … <LOCAL_CONFIG_QUERY>``: записи через NUL, внутри записи
    ключ и значение разделены переводом строки (значение может отсутствовать вовсе).
    Возвращается отсортированный кортеж ключей КАК ЕСТЬ (пустой — идти можно); сверка
    регистронезависимая, потому что регистр в выводе git — его деталь, а не гарантия.

    🔴 Это ALLOW-список, и это принципиально: перечень «опасных ключей» обходится дважды
    (``include.path`` и ``extensions.worktreeConfig`` ПРЯЧУТ свои ключи от ``--local`` —
    воспроизведено), а незнакомый ключ виден всегда. Цена — ложный отказ на ключе, который
    когда-нибудь начнёт писать сам git; он громкий и называет ключ, поэтому диагностируется
    за один взгляд. 🔴 Возвращаются только ИМЕНА: значение вправе быть секретом.
    """
    offending = {
        key
        for key in (record.partition("\n")[0].strip() for record in listing.split("\0"))
        if key and not _is_allowed(key.lower())
    }
    return tuple(sorted(offending))


def _is_allowed(key: str) -> bool:
    """Оставляет ли ключ (в нижнем регистре) наша собственная последовательность заведения."""
    if key in _ALLOWED_KEYS:
        return True
    if not key.startswith(_BRANCH_SECTION):
        return False
    # Имя ветки — подсекция, и точки в ней законны (``branch.bob/fix.v2.merge``), поэтому
    # разбор идёт от КОНЦА ключа. ``rpartition``, а не ``rsplit(…, 1)``: у него нет
    # параметра-числа, значение которого ничего не решает (мутация такой параметр крутит, а
    # мутанта не убить — он эквивалентный; лучше убрать сам параметр, чем триажить его).
    return key.rpartition(".")[2] in _ALLOWED_BRANCH_KEYS
