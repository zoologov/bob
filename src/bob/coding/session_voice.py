# --- Голос Боба (русский — язык проекта; Cyrillic look-alikes интенциональны) ---

# Берусь: Боб-оператор от первого лица принимает задачу и тут же направляет GUPPI
# (BOB-087.B2 — человечная реакция «взялся», не сухой статус).
_ACCEPTED = "О, любопытная задача — берусь. Сейчас прикину план и запущу GUPPI."

# План готов: Боб представляет план (детали набросал GUPPI) и зовёт к апруву. Хинт
# покрывает обе поверхности апрува — естественный язык в топике Боба и явную команду.
_PLAN_INTRO = "Прикинул, вот что планирую — GUPPI накидал детали. Глянь:"
_PLAN_HINT = (
    'Если ок — скажи «давай» (или /code approve). Передумал — «стоп» (/code stop).'
)
_NO_PLAN = "GUPPI плана не вернул — пустой прогон. Попробуем ещё раз?"

# Готово-PR: Боб-оператор реагирует на финиш («готово — вот PR»), GUPPI всё исполнил;
# напоминание про main (BOB-087.B2 — живая реакция, не «STATUS: DONE»).
_PR = (
    "Всё, готово — GUPPI закрыл задачу. Вот PR, глянь: {url}. "
    "Мержить — твоё дело, в main я не лезу."
)

# 🔴 Работа готова, но PR НЕ открыт (BOB-089, срез D). Боб работает в своём форке, и
# cross-repo PR из приватного форка ему недоступен (installation-токен скоупится на одну
# установку — не-цель PRD, обход не ищем). Поэтому реплика ЧЕСТНАЯ: он не приписывает себе
# открытие PR, а говорит, где лежит работа, почему дальше не может, и отдаёт форму, где
# owner жмёт «Create pull request». Соврать тут — то же, что доложить об уборке дерева,
# которое осталось на месте (пара к ``interactive.voice.stopped_persistent``).
_READY_FOR_PR = (
    "Всё, готово — GUPPI закрыл задачу, работа лежит в моём форке. "
    "Открыть PR сам не могу: в твой репозиторий у меня только чтение, так и задумано. "
    "Вот форма, жми «Create pull request»: {url}"
)

# Честные реакции провала/нет-правок/стопа — Боб-оператор от первого лица, GUPPI прибрал
# (BOB-087.B2 — на сбой человечное «чёрт», не сухой лог).
_NO_CHANGES = (
    "Глянул — GUPPI правок не внёс, коммитить нечего. "
    "PR не открываю, рабочую копию убрал."
)
_FAILED = "Чёрт, сорвалось: {detail}. GUPPI откатил рабочую копию."
_STOPPED = "Окей, тормознул. GUPPI свернулся, рабочую копию убрал."
# Кап нарратив-флуда (BOB-076): на длинном прогоне (много правок) Боб не частит строкой
# на каждое событие — после потолка шлёт ОДНУ реплику «продолжаю» и молчит до результата.
_NARRATION_CAPPED = (
    "GUPPI ещё в работе — не буду частить каждой правкой. "
    "Продолжаю; покажу результат, как закончит."
)

# Указатель dev-канала (BOB-082.3): при флаге ``coder.dev_dm`` живой firehose идёт в
# ЛИЧКУ owner'а, а групповой топик получает ОДНУ короткую строку (INV-5: группа не
# флудится) — «детали в личке».
_DEV_POINTER = "Работаю над кодом — детали в личке."

# Операционные отказы/статус — короткие реплики Боба (не на «горячем» пути канона).
_BUSY = "Я уже в работе над сессией — сначала закроем её («стоп» / /code stop)."
_CANNOT_APPROVE = (
    "Сейчас апрувить нечего — нет плана, ждущего добра "
    "(поставь задачу, я набросаю план)."
)
_NO_SESSION = "Активной сессии нет — я сейчас ничем не занят."
_STATUS_IDLE = "Активной сессии нет — я сейчас ничем не занят."
_STATUS_LINE = "Сессия «{task}» — состояние {state} (ветка {branch})."

# --- Индикатор работы: одна короткая строка editable-панели по фазам (BOB-046 .2) ---
# Не нарратив и не гейт — просто видимый owner маркер «процесс идёт», который use-case
# редактирует на месте (одно сообщение, не спам): план → выполняю → PR / провал / стоп.
_PANEL_PLANNING = "⏳ Прикидываю план…"
_PANEL_PLAN_READY = "📝 План готов — жду добро."
_PANEL_EXECUTING = "⚙️ GUPPI выполняет…"
_PANEL_PR = "✅ PR открыт."
# Пара к ``_PANEL_PR`` для форк-пути (BOB-089.D): PR не открыт, и панель этого не заявляет.
_PANEL_READY_FOR_PR = "✅ Работа готова — PR за тобой."
_PANEL_FAILED = "⚠️ Не получилось."
_PANEL_STOPPED = "⏹️ Остановил."


def accepted() -> str:
    """Реплика «берусь»: Боб принимает задачу и направляет GUPPI (старт сессии).

    Короткая реплика от первого лица, которую use-case шлёт owner, как только
    NL-задача принята — до построения плана. Чистая, без аргументов.
    """
    return _ACCEPTED


def plan(plan_text: str) -> str:
    """Реплика «план готов»: интро Боба + уже очищенный план + хинт апрува.

    ``plan_text`` — авторитетный, дедуплицированный и очищенный план (.1); он
    встраивается ДОСЛОВНО (markdown .1-путь его отрендерит). Пустой план →
    честная заметка про пустой прогон вместо тела.
    """
    body = plan_text if plan_text else _NO_PLAN
    return f"{_PLAN_INTRO}\n\n{body}\n\n{_PLAN_HINT}"


def pr(url: str) -> str:
    """Реплика «готово-PR»: Боб докладывает результат + ссылку, GUPPI всё исполнил."""
    return _PR.format(url=url)


def ready_for_pr(url: str) -> str:
    """Реплика «работа готова, PR за тобой»: ссылка на форму создания PR (BOB-089.D).

    🔴 Пара к :func:`pr`, и разница между ними — ЧЕСТНОСТЬ, а не стиль. Когда Боб работает
    в своём форке, PR он открыть не может (cross-repo PR из приватного форка недоступен
    installation-токену), поэтому эта реплика не приписывает ему совершённое действие: она
    говорит, что работа доведена и лежит в форке, называет причину и отдаёт ``url`` —
    предзаполненную форму (:func:`bob.coding.pr_link.compare_url`), где owner жмёт «Create
    pull request». Выдать это за открытый PR значило бы соврать о том, что owner проверит
    первым же нажатием.
    """
    return _READY_FOR_PR.format(url=url)


def no_changes() -> str:
    """Реплика «нет правок»: GUPPI ничего не изменил — честно, PR не открываем."""
    return _NO_CHANGES


def dev_pointer() -> str:
    """Указатель для группы (BOB-082.3): живой стрим — в личке, тут одна строка (INV-5)."""
    return _DEV_POINTER


def failed(detail: str) -> str:
    """Реплика «провал»: честная строка с ``detail``; GUPPI прибрал рабочую копию."""
    return _FAILED.format(detail=detail)


def stopped() -> str:
    """Реплика «остановил»: Боб погасил сессию, GUPPI свернулся и убрал копию."""
    return _STOPPED


def narration_capped() -> str:
    """Реплика «продолжаю»: единожды на прогоне, когда пер-событийный нарратив упёрся в кап.

    Боб перестаёт частить строкой на каждую правку (защита от флуда, BOB-076) и обещает
    показать результат. Финальный итог/провал/PR доходят всегда — кап только на
    промежуточный прогресс-нарратив.
    """
    return _NARRATION_CAPPED


def busy() -> str:
    """Отказ: уже идёт сессия — сначала её завершить."""
    return _BUSY


def cannot_approve() -> str:
    """Отказ: апрувить нечего — нет плана, ждущего добра."""
    return _CANNOT_APPROVE


def no_session() -> str:
    """Отказ/инфо: активной сессии нет."""
    return _NO_SESSION


def status_idle() -> str:
    """Статус: активной сессии нет."""
    return _STATUS_IDLE


def status_line(*, task: str, state: str, branch: str) -> str:
    """Статус идущей сессии: задача, состояние и ветка одной строкой."""
    return _STATUS_LINE.format(task=task, state=state, branch=branch)


def panel_planning() -> str:
    """Фаза панели «прикидываю план» — стартовая строка индикатора работы."""
    return _PANEL_PLANNING


def panel_plan_ready() -> str:
    """Фаза панели «план готов» — план собран, ждём добро owner."""
    return _PANEL_PLAN_READY


def panel_executing() -> str:
    """Фаза панели «выполняю» — GUPPI вносит правки по одобренному плану."""
    return _PANEL_EXECUTING


def panel_pr() -> str:
    """Финал панели «PR открыт» — успешное завершение сессии."""
    return _PANEL_PR


def panel_ready_for_pr() -> str:
    """Финал панели «работа готова, PR за тобой» — форк-путь без открытого PR (BOB-089.D).

    Пара к :func:`panel_pr`: панель — тоже owner-facing строка, и заявлять открытый PR там,
    где отдана лишь ссылка, ей запрещено ровно так же, как и реплике.
    """
    return _PANEL_READY_FOR_PR


def panel_failed() -> str:
    """Финал панели «не получилось» — провал/нет правок."""
    return _PANEL_FAILED


def panel_stopped() -> str:
    """Финал панели «остановил» — owner погасил сессию kill-switch'ем."""
    return _PANEL_STOPPED
