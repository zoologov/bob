"""session_voice — голос Боба на гейтах coding-сессии (BOB-041 .3).

Канон Бобиверса: **Боб — личность**, он дирижирует сессией от первого лица; **GUPPI —
сухой детерминированный исполнитель** («руки» без личности), которым Боб правит. Эти
билдеры — ЧИСТЫЕ детерминированные ШАБЛОНЫ (никакого LLM-вызова на сообщение:
латентность/стоимость): ключевые реплики сессии (берусь / план готов / готово-PR /
готово-но-PR-за-owner'ом / провал / нет-правок / остановил) — в персоне Боба, с GUPPI как
исполнителем, на которого Боб ссылается. Формулировки персона-окрашенные, но сдержанные —
гэги по чуть-чуть, без перебора.

Это голос (как Боб ЗВУЧИТ), а не машинерия безопасности: гейты/поток/изоляция
(BOB-039/040/.2) живут в use-case :mod:`~bob.coding.usecases.coding_assistant`
и не меняются — здесь только текст owner-facing сообщений. Все строки render-safe
(markdown .1-пути не ломается): встроенный план уже очищен апстримом.

🔴 BOB-087.E (bob-6u2): реплики ЖИВОГО ТЕРМИНАЛА (вход/выход режима, «сеанс кончился
сам», весь цикл возобновления) уехали в голос своего bounded context —
:mod:`bob.interactive.voice`. Здесь остался голос гейтед-кодера. Две строки —
:func:`stopped` и :func:`no_session` — общие для обоих (они про управление сессией, а
не про режим), и живой терминал ре-экспортирует их отсюда, а не дублирует.
"""

