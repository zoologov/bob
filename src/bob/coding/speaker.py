"""speaker — чистое ядро «кто озвучивает сообщение»: Боб или GUPPI (BOB-090.D1).

Канон Денниса Тейлора («Мы — Легион. Мы — Боб»), решение owner'а: **GUPPI —
несознательный интерфейс**. Он исполняет буквально, у него нет личности, мнения и
инициативы. Значит, служебное и машинное должно звучать ИМ — сухо и фактически, — а
живое и адресованное людям остаётся голосом Боба. Тогда скриптовые реплики перестают
быть проблемой человечности: скриптово звучит отдельный персонаж, которому это положено
по природе.

Одна ответственность: по ВИДУ сообщения назвать говорящего. Ни транспорта, ни ботов, ни
флагов — выбор канала делает потребитель вердикта (use-case + композиция), которые знают
про два нотификатора; ядро знает только канон.

🔴 Линия раздела (зафиксирована owner'ом ДО реализации):

* **механика** — сырой вывод инструментов, пошаговый нарратив прогона, технический
  статус/итог, «не найдено», техническое подтверждение → :data:`Speaker.GUPPI`;
* **живое** — реплики гейтов сессии, вход/выход режима, реакции и суждения, маркер
  присутствия и всё адресованное людям → :data:`Speaker.BOB`;
* **запрос разрешения — это Боб**, а не GUPPI. Это социальный акт (Боб защищает
  приватность owner'а и просит решения у человека), а не механика: механика — «инструмент
  вернул пусто», а не «человек просит доступ». Срез E говорит этим голосом.

🔴 Про честность гейта: вердикт — член перечисления, а mutmut подмену enum-члена не
порождает вовсе (MUTATION.md, урок bob-abk.34). Поэтому политика ЖИВЁТ В ТЕЛЕ
:func:`is_mechanical` отдельными сравнениями (выпадение любого вида даёт видимого
мутанта), а соответствие «вид → говорящий» держат содержательные юниты-таблица
истинности в ``tests/domain/coding/test_speaker.py``, проверенные саботажем.
"""

from __future__ import annotations

from enum import StrEnum

__all__ = ["MessageKind", "Speaker", "is_mechanical", "speaker_for"]


class Speaker(StrEnum):
    """Кто озвучивает сообщение: живой Боб или его несознательный исполнитель."""

    BOB = "bob"
    GUPPI = "guppi"


class MessageKind(StrEnum):
    """Вид сообщения — то единственное, по чему определяется говорящий.

    Механика (по канону — голос GUPPI):

    * :data:`TOOL_OUTPUT` — сырой вывод инструмента (живой поток запущенного claude);
    * :data:`RUN_EVENT` — пошаговый нарратив прогона («правлю файл», «гоняю тесты»);
    * :data:`RUN_STATUS` — технический статус/итог прогона («готово», «ошибка: …»);
    * :data:`NOTHING_FOUND` — «не найдено» / пустой результат инструмента;
    * :data:`TECHNICAL_ACK` — техническое подтверждение выполненного.

    Живое (голос Боба):

    * :data:`SESSION_GATE` — реплики гейтов сессии (берусь / план / готово-PR / провал /
      остановил): это его решения и обещания человеку, а не отчёт машины;
    * :data:`MODE_NOTICE` — вход/выход режима, «сеанс кончился сам»;
    * :data:`REACTION` — живая реакция или суждение («продолжаю; покажу результат»);
    * :data:`PRESENCE_MARK` — маркер присутствия самого Боба («печатает…», панель
      «прикидываю план»): он от первого лица и говорит о БОБЕ, а не о работе машины;
    * :data:`PERMISSION_REQUEST` — просьба разрешения (социальный акт, срез E);
    * :data:`ADDRESSED_TO_PERSON` — всё прочее, адресованное людям.
    """

    TOOL_OUTPUT = "tool_output"
    RUN_EVENT = "run_event"
    RUN_STATUS = "run_status"
    NOTHING_FOUND = "nothing_found"
    TECHNICAL_ACK = "technical_ack"
    SESSION_GATE = "session_gate"
    MODE_NOTICE = "mode_notice"
    REACTION = "reaction"
    PRESENCE_MARK = "presence_mark"
    PERMISSION_REQUEST = "permission_request"
    ADDRESSED_TO_PERSON = "addressed_to_person"


def is_mechanical(kind: MessageKind) -> bool:
    """Механика ли это — то, что по канону озвучивает сухой исполнитель.

    Состав перечислен ПОЭЛЕМЕНТНО в теле (а не набором-константой наверху файла):
    выпадение любого вида из механики тогда становится видимым мутантом, и гейт
    измеряет политику, а не форму записи (MUTATION.md, §«Порог и честность»).
    """
    return (
        kind is MessageKind.TOOL_OUTPUT
        or kind is MessageKind.RUN_EVENT
        or kind is MessageKind.RUN_STATUS
        or kind is MessageKind.NOTHING_FOUND
        or kind is MessageKind.TECHNICAL_ACK
    )


def speaker_for(kind: MessageKind) -> Speaker:
    """Назвать говорящего для ``kind``: механика → GUPPI, всё живое → Боб.

    Чистая функция без побочных эффектов: она НЕ выбирает бота и не знает про флаги —
    потребитель (use-case, композиция) переводит вердикт в канал. По умолчанию говорит
    Боб: всё, что не названо механикой явно, адресовано человеку и звучит живым голосом.
    """
    return Speaker.GUPPI if is_mechanical(kind) else Speaker.BOB
